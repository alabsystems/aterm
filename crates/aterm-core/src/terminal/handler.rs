/// Parse the exact coordinate-bearing OSC 133 payloads aterm itself queues.
/// Other OSC codes and OSC 133 D (which carries only an exit status) are not
/// absolute-row anchors and deliberately return `None`.
fn shell_event_row(payload: &str, code: u32) -> Option<(char, u64, u16)> {
    if code != 133 {
        return None;
    }
    let (command, rest) = payload.split_once(";row=")?;
    let command = match command {
        "A" => 'A',
        "B" => 'B',
        "C" => 'C',
        _ => return None,
    };
    let (row, col) = rest.split_once(";col=")?;
    Some((command, row.parse().ok()?, col.parse().ok()?))
}

/// The gates every program-originated reply passes, debiting the rate
/// limit when both open: the policy's `response any` verdict and the
/// response rate limit (the policy's bucket, else the legacy limiter).
/// Shared by [`TerminalHandler::send_response`] and the DEC 2031 push a program's own
/// output provokes (`reconcile_color_scheme_after_output`).
pub(super) fn program_response_admitted(
    policy: &mut super::policy_gates::PolicyState,
    transient: &mut TransientState,
    len: usize,
) -> bool {
    // Policy allow gate: a host that installs `response any = Drop`
    // suppresses every DA/DSR/DECRQSS/XTGETTCAP reply; no engine or a
    // fall-through decision allows. The probe (`ProbeKind::response_sink()`)
    // and origin are constants, so the verdict is compiled once per policy
    // (`policy_gates.rs`) and read here before the rate-limit debit.
    if !policy.gates().response_sink().resolve(true) {
        return false;
    }
    // Rate-limit gate: with a policy installed, its `"response"` bucket
    // decides, addressed by the slot `PolicyState` resolved at install time;
    // `None` means no engine and defers to the legacy
    // `ResponseRateLimiter` below. A policy without a `"response"` bucket
    // resolves to `RateLimitSlot::UNDECLARED`, which allows.
    let bytes = len as u64;
    let clock = aterm_policy::limits::SystemClock;
    if let Some(permitted) = policy.response_rate_limit_try_consume(bytes, &clock) {
        permitted
    } else {
        let legacy_clock = super::response_rate_limiter::SystemTime;
        transient
            .response_rate_limiter
            .try_consume(len, &legacy_clock)
    }
}

#[cfg(test)]
mod absolute_row_update_tests {
    use super::super::{
        Annotation, MarksState, OutputBlock, ShellIntegrationState, TerminalMark, TransientState,
    };
    use super::apply_absolute_row_update;

    #[test]
    fn splice_preserves_exclusive_end_boundaries_and_remaps_all_anchor_families() {
        let mut shell = ShellIntegrationState::new();
        let mut before = OutputBlock::new(0, 2, 0);
        before.end_row = Some(3);
        shell.output_blocks.push_back(before);
        let mut at = OutputBlock::new(1, 3, 0);
        at.end_row = Some(3);
        shell.output_blocks.push_back(at);

        let mut marks = MarksState::new();
        marks.marks.push_back(TerminalMark::new(0, 3, 0));
        marks
            .annotations
            .push_back(Annotation::new(0, 3, 0, "footer".into()));

        let mut revision = 0;
        let mut transient = TransientState::new();
        transient.osc_events.push(133, "A;row=3;col=0".into());
        transient.osc_events.push(133, "D;exit=0".into());
        transient.osc_events.push(7, "/tmp".into());
        apply_absolute_row_update(
            aterm_grid::AbsoluteRowUpdate::Splice { at: 3, inserted: 1 },
            &mut shell,
            &mut marks,
            &mut transient,
            &mut revision,
        );

        assert_eq!(shell.output_blocks[0].prompt_start_row, 2);
        assert_eq!(shell.output_blocks[0].end_row, Some(3));
        assert_eq!(shell.output_blocks[1].prompt_start_row, 4);
        assert_eq!(shell.output_blocks[1].end_row, Some(4));
        assert_eq!(marks.marks[0].row, 4);
        assert_eq!(marks.annotations[0].row, 4);
        assert_eq!(
            transient.osc_events.iter().cloned().collect::<Vec<_>>(),
            vec![
                (133, "A;row=4;col=0".into()),
                (133, "D;exit=0".into()),
                (7, "/tmp".into()),
            ]
        );
        assert_eq!(
            transient.osc_events.bytes(),
            "A;row=4;col=0D;exit=0/tmp".len()
        );
        assert_eq!(revision, 1);
    }

    #[test]
    fn invalidation_drops_only_coordinate_bearing_shell_events() {
        let mut shell = ShellIntegrationState::new();
        let mut marks = MarksState::new();
        let mut transient = TransientState::new();
        for event in [
            (133, "A;row=3;col=0".into()),
            (133, "B;row=3;col=1".into()),
            (133, "C;row=3;col=2".into()),
            (133, "D;exit=0".into()),
            (7, "/tmp".into()),
            (52, "clipboard".into()),
        ] {
            transient.osc_events.push(event.0, event.1);
        }
        let mut revision = 0;

        apply_absolute_row_update(
            aterm_grid::AbsoluteRowUpdate::Invalidate,
            &mut shell,
            &mut marks,
            &mut transient,
            &mut revision,
        );

        assert_eq!(
            transient.osc_events.iter().cloned().collect::<Vec<_>>(),
            vec![
                (133, "D;exit=0".into()),
                (7, "/tmp".into()),
                (52, "clipboard".into()),
            ]
        );
        assert_eq!(transient.osc_events.bytes(), "D;exit=0/tmpclipboard".len());
        assert_eq!(revision, 1);
    }
}


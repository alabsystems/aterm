/// Single-source mapping from `TerminalHandler` fields to `Terminal` borrow
/// paths.
///
/// Each entry: `handler_field: Type => terminal.borrow.path`
///
/// Generates:
/// - `TerminalHandler<'a>` struct (all fields as `pub(super) &'a mut`)
/// - `Terminal::split_for_process()` returning `(&mut Parser, TerminalHandler<'_>)`
///
/// Adding or removing a handler field is a one-line edit, and the struct and
/// its construction cannot drift apart.
///
/// Several Terminal sub-structs are passed as whole borrows:
///
/// - `transient` — response buffer, hyperlink, underline color, SGR stack,
///   VT52 state, sync start, last graphic char
macro_rules! define_terminal_handler {
    (
        $(
            $(#[$meta:meta])*
            $field:ident : $ty:ty => $($path:ident).+
        ),*
        $(,)?
    ) => {
        /// Handler struct for parser callbacks: mutable borrows of the
        /// terminal state VT processing needs, generated by
        /// [`define_terminal_handler!`] together with `split_for_process()`.
        pub(super) struct TerminalHandler<'a> {
            $(
                $(#[$meta])*
                pub(super) $field: &'a mut $ty,
            )*
        }

        impl super::Terminal {
            /// Split `Terminal` into disjoint parser and handler borrows for VT
            /// processing. Generated by [`define_terminal_handler!`].
            pub(super) fn split_for_process(
                &mut self,
            ) -> (&mut crate::parser::Parser, TerminalHandler<'_>) {
                (
                    &mut self.parser,
                    TerminalHandler {
                        $(
                            $(#[$meta])*
                            $field: &mut self.$($path).+,
                        )*
                    },
                )
            }
        }
    };
}


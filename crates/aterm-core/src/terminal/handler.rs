//! Terminal escape sequence handler: struct definition and routing.
//!
//! `TerminalHandler` holds mutable borrows of the terminal state VT processing
//! needs. Its methods are split by concern:
//!
//! - Parser actions (`handler_actions.rs`): the `ActionSink` impl, receiving
//!   parsed events and dispatching to typed handler methods (uses `parser`,
//!   `charset`).
//! - State transitions (`handler_state.rs`): grid/mode mutations such as
//!   cursor movement, erase, scroll, insert/delete, DECSTR, DSR/DA (uses
//!   `grid`, `bidi`, `config`, `vt_level`).
//! - Protocol dispatch (`handler_csi.rs`, `handler_esc.rs`, `handler_dcs.rs`):
//!   routing from parser actions to state transitions or side effects.
//! - Side effects (inline in protocol handlers): callbacks and external
//!   services (bell, notifications, clipboard, window ops).
// Zero tolerance: the bell's rate limit judges only the injected instant (a
// clock read here was an incident), so no `#[expect]` may excuse one.

impl TerminalHandler<'_> {
    /// Fail-closed marker for the DEC 2026 close+reopen present license: called
    /// once per completed parser action (a bulk text run is one action), never
    /// per DCS/APC payload byte.
    #[inline]
    pub(super) fn note_sync_open_action(&mut self) {
        if self.modes.synchronized_output {
            self.transient.sync_open_dirty = true;
        }
        if self.transient.app_sync_open {
            self.transient.app_sync_dirty = true;
        }
    }

    /// Apply any logical-row insertion before a protocol action creates new
    /// absolute-row metadata, preserving parser order: metadata emitted after a
    /// scroll must not be taken for an anchor that existed before it.
    pub(super) fn sync_absolute_row_metadata(&mut self) {
        if let Some(update) = self.grid.take_absolute_row_update() {
            apply_absolute_row_update(
                update,
                self.shell,
                self.marks_state,
                self.transient,
                self.absolute_row_revision,
            );
        }
    }

    pub(super) fn sgr_style(&mut self) -> SgrStyleHandler<'_> {
        SgrStyleHandler {
            grid: &mut *self.grid,
            style: &mut *self.style,
            transient: &mut *self.transient,
        }
    }

    pub(super) fn cursor_state(&mut self) -> CursorStateHandler<'_> {
        CursorStateHandler {
            grid: &mut *self.grid,
            style: &mut *self.style,
            modes: &mut *self.modes,
            charset: &mut *self.charset,
            cursor_save: &mut *self.cursor_save,
            underline_color: &mut self.transient.current_underline_color,
            has_transient_extras: &mut self.transient.has_transient_extras,
            has_hyperlink: self.transient.current_hyperlink.is_some(),
        }
    }

    /// Handle BEL (0x07): fire the bell callback, rate-limited to one per
    /// 100 ms against BEL floods.
    pub(super) fn handle_bell(&mut self) {
        const MIN_BELL_INTERVAL: std::time::Duration = std::time::Duration::from_millis(100);

        // Observe the batch's logical instant (Clock seam) rather than reading
        // the wall clock here, so bell throttling replays deterministically.
        let now = self.transient.process_now;
        if let Some(last) = *self.last_bell_time {
            if now.duration_since(last) < MIN_BELL_INTERVAL {
                return;
            }
        }
        *self.last_bell_time = Some(now);

        // Edge-triggered flag for poll-based hosts (drained by Terminal::drain_bell),
        // set alongside — not instead of — the existing synchronous callback.
        self.transient.bell_pending = true;
        // Monotonic running total (past the throttle, so it matches the callback
        // count) for watermark observers like the `subscribe events` stream.
        *self.bell_total = self.bell_total.saturating_add(1);

        if let Some(callback) = self.bell_callback {
            callback();
        }
    }

    /// Invalidate the render-time BiDi projection of every stored row: mode or
    /// direction changes can reorder existing cells on the next snapshot, so
    /// mark full damage for damage-keyed frontends.
    #[inline]
    pub(super) fn invalidate_bidi_all(&mut self) {
        self.grid.damage_mut().mark_full();
    }

    /// Perform a line feed, honoring DECLRMM left/right margins. Inline-image
    /// placements (Kitty, iTerm2, sixel) live in cell extras and move with
    /// their cells.
    #[inline]
    pub(super) fn margined_line_feed(&mut self, left_right_margin_mode: bool) {
        self.grid.line_feed_margined(left_right_margin_mode);
    }

    /// Write a response (DSR/DA and other replies) to the response buffer.
    ///
    /// Two limits apply:
    /// 1. [`MAX_RESPONSE_BUFFER_SIZE`] caps the total bytes waiting for the
    ///    host to drain.
    /// 2. The [`ResponseRateLimiter`][rl] caps the generation rate, against
    ///    DSR/DA amplification when the host drains in a tight loop.
    ///
    /// Responses failing either are dropped silently.
    ///
    /// [rl]: super::response_rate_limiter::ResponseRateLimiter
    ///
    /// `_cap` is a zero-sized [`ResponseCapability`][rc] proving the caller is
    /// inside a parser-dispatched CSI/ESC/OSC/DCS frame, the only legitimate
    /// origin of a PTY response; code outside such a frame cannot construct it.
    ///
    /// [rc]: super::response_capability::ResponseCapability
    pub(super) fn send_response(
        &mut self,
        _cap: &super::response_capability::ResponseCapability,
        response: &[u8],
    ) {
        if !self.can_append_response_bytes(response.len()) {
            return;
        }
        // Policy allow gate: a host that installs `response any = Drop`
        // suppresses every DA/DSR/DECRQSS/XTGETTCAP reply; no engine or a
        // fall-through decision allows. The probe (`ProbeKind::response_sink()`)
        // and origin are constants, so the verdict is compiled once per policy
        // (`policy_gates.rs`) and read here before the rate-limit debit.
        if !self.policy.gates().response_sink().resolve(true) {
            return;
        }
        // Rate-limit gate: with a policy installed, its `"response"` bucket
        // decides, addressed by the slot `PolicyState` resolved at install time;
        // `None` means no engine and defers to the legacy
        // `ResponseRateLimiter` below. A policy without a `"response"` bucket
        // resolves to `RateLimitSlot::UNDECLARED`, which allows.
        let bytes = response.len() as u64;
        let clock = aterm_policy::limits::SystemClock;
        let permitted =
            if let Some(permitted) = self.policy.response_rate_limit_try_consume(bytes, &clock) {
                permitted
            } else {
                let legacy_clock = super::response_rate_limiter::SystemTime;
                self.transient
                    .response_rate_limiter
                    .try_consume(response.len(), &legacy_clock)
            };
        if !permitted {
            return;
        }
        // Fallible allocation: the total is already capped, but reserve before
        // appending so a real OOM (or an armed `response.append_alloc` fault)
        // drops this response instead of aborting the process.
        if crate::fault::triggered("response.append_alloc")
            || self
                .transient
                .response_buffer
                .try_reserve(response.len())
                .is_err()
        {
            return;
        }
        self.transient.response_buffer.extend_from_slice(response);
    }

    /// Returns whether appending `additional_len` would stay within the cap.
    pub(super) fn can_append_response_bytes(&self, additional_len: usize) -> bool {
        self.transient
            .response_buffer
            .len()
            .saturating_add(additional_len)
            <= MAX_RESPONSE_BUFFER_SIZE
    }

    /// Queue an OSC app-event `(code, payload)` for the host to poll via
    /// `Terminal::take_osc_event`: decoded payloads (OSC 52 clipboard, OSC 7
    /// cwd, OSC 133 marks), separate from PTY replies. Bounded by count and by
    /// bytes (`OscEventQueue`), even on a host that never drains it.
    pub(super) fn queue_osc_event(&mut self, code: u32, payload: String) {
        self.transient.osc_events.push(code, payload);
    }

    /// Filter DCS data for echoing in responses: keep only printable ASCII
    /// (0x20-0x7E), since escape sequences echoed back to a shell could inject
    /// commands. See dgl.cx/2023/09/ansi-terminal-security.
    pub(super) fn filter_dcs_data_for_response(data: &[u8]) -> Vec<u8> {
        data.iter()
            .copied()
            .filter(|&b| (0x20..=0x7E).contains(&b))
            .collect()
    }
}

/// Apply a grid coordinate-space update to every durable absolute-row anchor.
///
/// Point/start anchors at the splice move forward. `OutputBlock::end_row` is
/// exclusive, so a pre-splice span ending exactly at the insertion boundary
/// stays put, while a whole block starting at that boundary moves together.
pub(super) fn apply_absolute_row_update(
    update: aterm_grid::AbsoluteRowUpdate,
    shell: &mut super::ShellIntegrationState,
    marks_state: &mut super::MarksState,
    transient: &mut TransientState,
    absolute_row_revision: &mut u64,
) {
    *absolute_row_revision = absolute_row_revision.saturating_add(1);
    let aterm_grid::AbsoluteRowUpdate::Splice { at, inserted } = update else {
        shell.command_marks.clear();
        shell.current_mark = None;
        shell.output_blocks.clear();
        shell.current_block = None;
        marks_state.marks.clear();
        marks_state.annotations.clear();
        // Coordinate-bearing events were queued before the coordinate space
        // became unknowable. Keep unrelated OSC events and row-free D events,
        // but never deliver A/B/C with a row known to be wrong.
        transient
            .osc_events
            .retain(|code, payload| shell_event_row(payload, code).is_none());
        return;
    };

    transient.osc_events.rewrite(|code, payload| {
        let (command, row, col) = shell_event_row(payload, code)?;
        (row >= at).then(|| format!("{command};row={};col={col}", row.saturating_add(inserted)))
    });

    let shift_point = |row: &mut u64| {
        if *row >= at {
            *row = row.saturating_add(inserted);
        }
    };
    let shift_optional_point = |row: &mut Option<u64>| {
        if let Some(row) = row {
            shift_point(row);
        }
    };

    for mark in shell
        .command_marks
        .iter_mut()
        .chain(shell.current_mark.iter_mut())
    {
        shift_point(&mut mark.prompt_start_row);
        shift_optional_point(&mut mark.command_start_row);
        shift_optional_point(&mut mark.output_start_row);
        shift_optional_point(&mut mark.output_end_row);
    }

    for block in shell
        .output_blocks
        .iter_mut()
        .chain(shell.current_block.iter_mut())
    {
        let starts_at_or_after_splice = block.prompt_start_row >= at;
        shift_point(&mut block.prompt_start_row);
        shift_optional_point(&mut block.command_start_row);
        shift_optional_point(&mut block.output_start_row);
        if let Some(end_row) = &mut block.end_row
            && (*end_row > at || starts_at_or_after_splice)
        {
            *end_row = end_row.saturating_add(inserted);
        }
    }

    for mark in &mut marks_state.marks {
        shift_point(&mut mark.row);
    }
    for annotation in &mut marks_state.annotations {
        shift_point(&mut annotation.row);
    }
}

/// Parse the exact coordinate-bearing OSC 133 payloads aterm itself queues.
/// Other OSC codes and OSC 133 D (which carries only an exit status) are not
/// absolute-row anchors and deliberately return `None`.
fn shell_event_row(payload: &str, code: u32) -> Option<(char, u64, u16)> {
    if code != 133 {
        return None;
    }
    let (command, rest) = payload.split_once(";row=")?;
    let command = match command {
        "A" => 'A',
        "B" => 'B',
        "C" => 'C',
        _ => return None,
    };
    let (row, col) = rest.split_once(";col=")?;
    Some((command, row.parse().ok()?, col.parse().ok()?))
}

#[cfg(test)]
mod absolute_row_update_tests {
    use super::super::{
        Annotation, MarksState, OutputBlock, ShellIntegrationState, TerminalMark, TransientState,
    };
    use super::apply_absolute_row_update;

    #[test]
    fn splice_preserves_exclusive_end_boundaries_and_remaps_all_anchor_families() {
        let mut shell = ShellIntegrationState::new();
        let mut before = OutputBlock::new(0, 2, 0);
        before.end_row = Some(3);
        shell.output_blocks.push_back(before);
        let mut at = OutputBlock::new(1, 3, 0);
        at.end_row = Some(3);
        shell.output_blocks.push_back(at);

        let mut marks = MarksState::new();
        marks.marks.push_back(TerminalMark::new(0, 3, 0));
        marks
            .annotations
            .push_back(Annotation::new(0, 3, 0, "footer".into()));

        let mut revision = 0;
        let mut transient = TransientState::new();
        transient.osc_events.push(133, "A;row=3;col=0".into());
        transient.osc_events.push(133, "D;exit=0".into());
        transient.osc_events.push(7, "/tmp".into());
        apply_absolute_row_update(
            aterm_grid::AbsoluteRowUpdate::Splice { at: 3, inserted: 1 },
            &mut shell,
            &mut marks,
            &mut transient,
            &mut revision,
        );

        assert_eq!(shell.output_blocks[0].prompt_start_row, 2);
        assert_eq!(shell.output_blocks[0].end_row, Some(3));
        assert_eq!(shell.output_blocks[1].prompt_start_row, 4);
        assert_eq!(shell.output_blocks[1].end_row, Some(4));
        assert_eq!(marks.marks[0].row, 4);
        assert_eq!(marks.annotations[0].row, 4);
        assert_eq!(
            transient.osc_events.iter().cloned().collect::<Vec<_>>(),
            vec![
                (133, "A;row=4;col=0".into()),
                (133, "D;exit=0".into()),
                (7, "/tmp".into()),
            ]
        );
        assert_eq!(
            transient.osc_events.bytes(),
            "A;row=4;col=0D;exit=0/tmp".len()
        );
        assert_eq!(revision, 1);
    }

    #[test]
    fn invalidation_drops_only_coordinate_bearing_shell_events() {
        let mut shell = ShellIntegrationState::new();
        let mut marks = MarksState::new();
        let mut transient = TransientState::new();
        for event in [
            (133, "A;row=3;col=0".into()),
            (133, "B;row=3;col=1".into()),
            (133, "C;row=3;col=2".into()),
            (133, "D;exit=0".into()),
            (7, "/tmp".into()),
            (52, "clipboard".into()),
        ] {
            transient.osc_events.push(event.0, event.1);
        }
        let mut revision = 0;

        apply_absolute_row_update(
            aterm_grid::AbsoluteRowUpdate::Invalidate,
            &mut shell,
            &mut marks,
            &mut transient,
            &mut revision,
        );

        assert_eq!(
            transient.osc_events.iter().cloned().collect::<Vec<_>>(),
            vec![
                (133, "D;exit=0".into()),
                (7, "/tmp".into()),
                (52, "clipboard".into()),
            ]
        );
        assert_eq!(transient.osc_events.bytes(), "D;exit=0/tmpclipboard".len());
        assert_eq!(revision, 1);
    }
}


/// RFC 1951 3.2.6 fixed literal/length code lengths.
fn fixed_lit_lengths() -> Vec<u16> {
    (0..288)
        .map(|sym| match sym {
            0..=143 => 8u16,
            144..=255 => 9,
            256..=279 => 7,
            _ => 8,
        })
        .collect()
}

/// The dynamic lane's literal/length code. Tiers sum to Kraft 1 over exactly
/// 286 symbols and span 3..13 bits, so the stream contains both table-resolvable
/// codes (<= 9 bits) and fallback codes (> 9 bits).
fn dynamic_lit_code() -> CanonCode {
    // 4/8 + 8/32 + 16/128 + 2/256 + 32/512 + 64/2048 + 32/4096 + 128/8192 == 1.
    const TIERS: [(usize, u16); 8] = [
        (4, 3),
        (8, 5),
        (16, 7),
        (2, 8),
        (32, 9),
        (64, 11),
        (32, 12),
        (128, 13),
    ];
    // Priority: the 62 hot byte values first, then end-of-block and the
    // length codes the generator actually emits, then everything else.
    let mut priority: Vec<usize> = (0..62).collect();
    priority.push(256);
    priority.extend(257..286);
    priority.extend(62..256);
    assert_eq!(priority.len(), 286);
    CanonCode::build(lengths_from_tiers(286, &TIERS, &priority))
}

/// The dynamic lane's distance code: 2/4 + 4/16 + 8/64 + 16/128 == 1 over
/// exactly 30 symbols, longest word 7 bits — every distance is a table hit,
/// which is also true of real dynamic blocks.
fn dynamic_dist_code() -> CanonCode {
    const TIERS: [(usize, u16); 4] = [(2, 2), (4, 4), (8, 6), (16, 7)];
    let priority: Vec<usize> = (0..30).collect();
    CanonCode::build(lengths_from_tiers(30, &TIERS, &priority))
}

/// Encode the literal/length + distance code lengths with a code-length code,
/// emitting every length literally (no 16/17/18 run codes). The code-length
/// code's own lengths ride in 3-bit fields, so it must have no word longer than
/// 7 bits — the tier spec below tops out at 4.
fn write_dynamic_header(w: &mut BitWriter, lit: &CanonCode, dist: &CanonCode) -> CanonCode {
    let mut used: Vec<usize> = lit
        .lengths
        .iter()
        .chain(dist.lengths.iter())
        .map(|&l| l as usize)
        .collect::<std::collections::BTreeSet<_>>()
        .into_iter()
        .collect();
    used.sort_unstable();
    // 1/4 + 2/8 + 8/16 == 1 over 11 symbols, longest word 4 bits.
    assert_eq!(
        used.len(),
        11,
        "the code-length tier spec is written for exactly 11 distinct lengths"
    );
    const TIERS: [(usize, u16); 3] = [(1, 2), (2, 3), (8, 4)];
    let cl = CanonCode::build(lengths_from_tiers(19, &TIERS, &used));

    w.bits_lsb(286 - 257, 5); // HLIT
    w.bits_lsb(30 - 1, 5); // HDIST
    w.bits_lsb(19 - 4, 4); // HCLEN
    for &slot in &CLCL_ORDER {
        w.bits_lsb(u32::from(cl.lengths[slot]), 3);
    }
    for &l in lit.lengths.iter().chain(dist.lengths.iter()) {
        cl.put(w, l as usize);
    }
    cl
}

fn write_tokens(w: &mut BitWriter, tokens: &[Token], lit: &CanonCode, dist: &CanonCode) {
    for tok in tokens {
        match *tok {
            Token::Literal(b) => lit.put(w, b as usize),
            Token::Match(len, d) => {
                let li = LENGTH_BASE
                    .iter()
                    .rposition(|&b| b <= len)
                    .expect("length below the smallest base");
                lit.put(w, 257 + li);
                w.bits_lsb(u32::from(len - LENGTH_BASE[li]), LENGTH_EXTRA[li]);
                let di = DIST_BASE
                    .iter()
                    .rposition(|&b| b <= d)
                    .expect("distance below the smallest base");
                dist.put(w, di);
                w.bits_lsb(u32::from(d - DIST_BASE[di]), DIST_EXTRA[di]);
            }
        }
    }
}

fn adler32(data: &[u8]) -> u32 {
    let (mut a, mut b) = (1u32, 0u32);
    for chunk in data.chunks(5552) {
        for &byte in chunk {
            a = a.wrapping_add(u32::from(byte));
            b = b.wrapping_add(a);
        }
        a %= 65521;
        b %= 65521;
    }
    (b << 16) | a
}

fn zlib_wrap(deflate: Vec<u8>, plain: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(deflate.len() + 6);
    out.extend_from_slice(&[0x78, 0x9c]); // CM=8, CINFO=7, FCHECK-valid
    out.extend_from_slice(&deflate);
    out.extend_from_slice(&adler32(plain).to_be_bytes());
    out
}

/// One BTYPE=1 (fixed Huffman) block holding the whole token stream.
fn encode_fixed(plain: &[u8], tokens: &[Token]) -> Vec<u8> {
    let lit = CanonCode::build(fixed_lit_lengths());
    let dist = CanonCode::build(vec![5u16; 32]);
    let mut w = BitWriter::empty();
    w.bits_lsb(1, 1); // BFINAL
    w.bits_lsb(1, 2); // BTYPE = 01, fixed
    write_tokens(&mut w, tokens, &lit, &dist);
    lit.put(&mut w, 256);
    zlib_wrap(w.finish(), plain)
}

/// `blocks` BTYPE=2 (dynamic Huffman) blocks, splitting the token stream evenly.
/// One block is the image case; hundreds of tiny blocks is the table-build
/// regression case.
fn encode_dynamic(plain: &[u8], tokens: &[Token], blocks: usize) -> Vec<u8> {
    let lit = dynamic_lit_code();
    let dist = dynamic_dist_code();
    let mut w = BitWriter::empty();
    let per = tokens.len().div_ceil(blocks.max(1));
    let chunks: Vec<&[Token]> = tokens.chunks(per.max(1)).collect();
    for (i, chunk) in chunks.iter().enumerate() {
        let last = u32::from(i + 1 == chunks.len());
        w.bits_lsb(last, 1); // BFINAL
        w.bits_lsb(2, 2); // BTYPE = 10, dynamic
        write_dynamic_header(&mut w, &lit, &dist);
        write_tokens(&mut w, chunk, &lit, &dist);
        lit.put(&mut w, 256);
    }
    zlib_wrap(w.finish(), plain)
}


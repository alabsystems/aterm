struct Workload {
    name: &'static str,
    /// The compressed stream fed to `zlib_decompress`.
    stream: Vec<u8>,
    /// The bytes it must decode to.
    plain: Vec<u8>,
    /// Fraction of emitted Huffman symbols whose code is short enough for the
    /// root table. Computed from the encoder's own code lengths, so it is exact.
    table_hit_share: f64,
    /// Number of DEFLATE blocks — the multiplier on per-table build cost.
    blocks: usize,
}

fn hit_share(tokens: &[Token], lit: &CanonCode, dist: &CanonCode) -> f64 {
    let mut hits = 0usize;
    let mut total = 0usize;
    for tok in tokens {
        let (sym_len, extra) = match *tok {
            Token::Literal(b) => (lit.lengths[b as usize], None),
            Token::Match(len, d) => {
                let li = LENGTH_BASE.iter().rposition(|&b| b <= len).unwrap_or(0);
                let di = DIST_BASE.iter().rposition(|&b| b <= d).unwrap_or(0);
                (lit.lengths[257 + li], Some(dist.lengths[di]))
            }
        };
        total += 1;
        if sym_len <= ROOT_BITS {
            hits += 1;
        }
        if let Some(dl) = extra {
            total += 1;
            if dl <= ROOT_BITS {
                hits += 1;
            }
        }
    }
    hits as f64 / total as f64
}

fn workloads() -> Vec<Workload> {
    let (plain_fixed, tokens_fixed) = generate(1 << 20, 70, 0x1234_5678_9abc_def0);
    let fixed_lit = CanonCode::build(fixed_lit_lengths());
    let fixed_dist = CanonCode::build(vec![5u16; 32]);
    let fixed = Workload {
        name: "fixed_1mib",
        stream: encode_fixed(&plain_fixed, &tokens_fixed),
        table_hit_share: hit_share(&tokens_fixed, &fixed_lit, &fixed_dist),
        plain: plain_fixed,
        blocks: 1,
    };

    let (plain_dyn, tokens_dyn) = generate(4 << 20, 70, 0x0fed_cba9_8765_4321);
    let dyn_lit = dynamic_lit_code();
    let dyn_dist = dynamic_dist_code();
    let dynamic = Workload {
        name: "dynamic_4mib",
        stream: encode_dynamic(&plain_dyn, &tokens_dyn, 1),
        table_hit_share: hit_share(&tokens_dyn, &dyn_lit, &dyn_dist),
        plain: plain_dyn,
        blocks: 1,
    };

    // ~400 blocks over 256 KiB: ~640 bytes of output per block, so three Huffman
    // tables are built for every few hundred decoded symbols.
    let (plain_tiny, tokens_tiny) = generate(256 << 10, 70, 0x5555_aaaa_3333_cccc);
    let tiny = Workload {
        name: "tiny_dynamic_blocks",
        stream: encode_dynamic(&plain_tiny, &tokens_tiny, 400),
        table_hit_share: hit_share(&tokens_tiny, &dyn_lit, &dyn_dist),
        plain: plain_tiny,
        blocks: 400,
    };

    vec![fixed, dynamic, tiny]
}

/// Prove each lane decodes to EXACTLY its source (so the hand-written encoder is
/// not quietly producing a stream that errors out after four symbols), and prove
/// the table-hit split each lane was designed for.
///
/// Two-sided on the thing under test: `fixed_1mib` must be ALL table hits (the
/// fixed alphabet's longest code is exactly ROOT_BITS), while `dynamic_4mib`
/// must be a genuine MIX — if it ever became all-hits or all-fallback it would
/// stop bracketing the change and start measuring one half of it.
fn verify_reaches_target(w: &Workload) {
    let decoded = zlib_decompress(&w.stream, 32 << 20)
        .unwrap_or_else(|e| panic!("{}: the generated stream does not decode: {e:?}", w.name));
    assert_eq!(
        decoded.len(),
        w.plain.len(),
        "{}: decoded length differs from the source",
        w.name
    );
    assert!(
        decoded == w.plain,
        "{}: decoded bytes differ from the source — the encoder is wrong and \
         this lane measures nothing meaningful",
        w.name
    );
    match w.name {
        "fixed_1mib" => assert!(
            w.table_hit_share > 0.999,
            "{}: table-hit share is {:.3}, but the fixed alphabet's longest code \
             is exactly ROOT_BITS so every symbol must resolve in the table",
            w.name,
            w.table_hit_share
        ),
        _ => assert!(
            (0.50..0.90).contains(&w.table_hit_share),
            "{}: table-hit share is {:.3} — this lane must exercise BOTH the \
             table and the bit-at-a-time fallback, or it measures only half the \
             change",
            w.name,
            w.table_hit_share
        ),
    }
    assert!(
        w.blocks == 1 || w.blocks >= 100,
        "{}: the block-count lanes must be far apart to separate per-symbol \
         decode cost from per-table build cost",
        w.name
    );
}

fn inflate_zlib(c: &mut Criterion) {
    let mut group = c.benchmark_group("inflate_zlib");
    group.sample_size(20);
    for w in workloads() {
        verify_reaches_target(&w);
        group.throughput(Throughput::Bytes(w.plain.len() as u64));
        group.bench_with_input(BenchmarkId::from_parameter(w.name), &w, |b, w| {
            b.iter(|| {
                let out = zlib_decompress(black_box(&w.stream), 32 << 20);
                let _ = black_box(out.map(|v| v.len()));
            });
        });
    }
    group.finish();
}

criterion_group!(benches, inflate_zlib);
criterion_main!(benches);

/// The 8x8 bitmap for `c`, or `None` when no supported family covers it.
///
/// `None` is a real answer, not a failure: the material sampler SKIPS an
/// unsupported code point rather than substituting a different-looking
/// character, which is what keeps literal mode's "these are your actual
/// characters" contract honest.
#[must_use]
pub(crate) fn bitmap(c: char) -> Option<[u8; 8]> {
    let cp = c as u32;
    let idx = GLYPHS.binary_search_by_key(&cp, |&(key, _)| key).ok()?;
    GLYPHS.get(idx).map(|&(_, rows)| rows)
}

#[cfg(test)]
mod tests {
    use super::{GLYPHS, bitmap};

    /// The binary search is only correct on a sorted table, and the table is
    /// generated — so the ordering is asserted here rather than trusted.
    #[test]
    fn the_table_is_sorted_and_has_no_duplicates() {
        for pair in GLYPHS.windows(2) {
            let (a, b) = (pair[0].0, pair[1].0);
            assert!(a < b, "table out of order at U+{a:04X} / U+{b:04X}");
        }
    }

    /// No blank glyphs: the old lookup filtered them, so an entry that is all
    /// zeros would be a `Some` where the retired crate answered `None`.
    #[test]
    fn no_glyph_is_blank() {
        for &(cp, rows) in &GLYPHS {
            assert!(
                rows.iter().any(|&r| r != 0),
                "U+{cp:04X} is a blank glyph and should not be in the table"
            );
        }
    }

    /// Spot checks that survive a regenerated table: the families the material
    /// sampler advertises are all actually present, and something outside them
    /// is absent.
    #[test]
    fn every_advertised_family_is_present() {
        for (label, ch) in [
            ("basic latin", 'A'),
            ("latin-1", 'e'),
            ("greek", '\u{3b1}'),
            ("box drawing", '\u{2500}'),
            ("block elements", '\u{2588}'),
            ("hiragana", '\u{3042}'),
        ] {
            assert!(bitmap(ch).is_some(), "{label} missing from the table");
        }
        assert!(bitmap(' ').is_none(), "a blank must stay unsupported");
        assert!(
            bitmap('\u{4e00}').is_none(),
            "CJK is not a supported family"
        );
    }
}

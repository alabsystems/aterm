//! `status` over a fake channel.

use atpkg_publish::channel::status;
use atpkg_publish::testkit::Keys;

use super::{Doc, Rig};

const LAPSED: &str = "2026-01-01T00:00:00Z";

fn lapsed_doc() -> Doc {
    let mut doc = Doc::new(21, &[("ay", 5)]);
    doc.valid_until = LAPSED.to_string();
    doc
}

#[test]
fn a_lapsed_head_is_described_and_marked_lapsed() {
    let rig = Rig::new("status-lapsed");
    rig.publish_head(&lapsed_doc());
    let lines = status::lines(&rig.ctx, None).expect("a lapsed head is still described");
    assert!(lines.iter().any(|l| l.contains("LAPSED:")), "{lines:?}");

    let dir = rig.path("quad");
    rig.quad_dir(&dir, &lapsed_doc());
    let on_disk = status::lines(&rig.ctx, Some(&dir)).expect("a lapsed quad on disk");
    assert!(on_disk.iter().any(|l| l.contains("LAPSED:")), "{on_disk:?}");

    let fresh = Rig::new("status-fresh");
    fresh.publish_head(&Doc::new(21, &[("ay", 5)]));
    let lines = status::lines(&fresh.ctx, None).expect("a fresh head");
    assert!(!lines.iter().any(|l| l.contains("LAPSED")), "{lines:?}");
}

#[test]
fn a_foreign_quad_is_refused_whatever_its_horizon() {
    let rig = Rig::new("status-foreign");
    let other = Keys::mint("m9", &[]);
    for doc in [lapsed_doc(), Doc::new(21, &[("ay", 5)])] {
        let dir = rig.path(&format!("foreign-{}", doc.valid_until.replace(':', "")));
        other.write_quad(&dir, &doc.render(&other));
        assert!(
            status::lines(&rig.ctx, Some(&dir)).is_err(),
            "{}",
            doc.valid_until
        );
    }
}

#[test]
fn the_live_codex_row_is_said_carried_not_drift() {
    let rig = Rig::new("status-codex");
    let mut doc = Doc::new(71, &[("ay", 5), ("codex", 2_026_101_501)]);
    for p in &mut doc.programs {
        if p.0 == "codex" {
            p.1 = "aterm".into();
        }
    }
    rig.publish_head(&doc);
    let lines = status::lines(&rig.ctx, None).expect("the head");
    assert!(
        lines.iter().any(|l| l.starts_with(
            "[programs.codex] names repo \"aterm\", not ALab's \"codex-alab\": carried as it stands"
        )),
        "{lines:?}"
    );
    assert!(!lines.iter().any(|l| l.contains("drift")), "{lines:?}");

    let alab = Rig::new("status-codex-alab");
    alab.publish_head(&Doc::new(71, &[("ay", 5), ("codex", 2_026_101_601)]));
    let lines = status::lines(&alab.ctx, None).expect("the head");
    assert!(
        !lines.iter().any(|l| l.contains("[programs.codex]")),
        "{lines:?}"
    );
}

#[test]
fn the_head_names_its_producer_and_flags_the_retired_shell_publisher() {
    let rig = Rig::new("status-producer");
    let body = Doc::new(77, &[("ay", 5)]).render(&rig.keys);
    let cases = [
        (
            "rust",
            atpkg_publish::channel::index::HEAD_LINE.to_string(),
            "producer: atpkg-publish index",
        ),
        (
            "shell",
            "# Auto-generated by tools/atpkg-index.sh — the MACHINE-signed allow-list.".into(),
            "producer: tools/atpkg-index.sh — RETIRED SHELL PUBLISHER",
        ),
        ("hand", "# written by hand".into(), "producer: unknown"),
    ];
    for (name, head, want) in cases {
        let dir = rig.path(&format!("quad-{name}"));
        rig.keys.write_quad(&dir, &format!("{head}\n{body}"));
        let lines = status::lines(&rig.ctx, Some(&dir)).expect("the quad verifies");
        assert!(
            lines.get(1).is_some_and(|l| l.starts_with(want)),
            "{name}: {lines:?}"
        );
        assert_eq!(
            lines.iter().any(|l| l.contains("RETIRED SHELL PUBLISHER")),
            name == "shell",
            "only the shell's head is flagged: {lines:?}"
        );
    }
}

#[test]
fn release_report_uses_signed_product_versions_host_dates_and_target_overlays() {
    const MAC: &str = "aarch64-apple-darwin";
    const LINUX: &str = "x86_64-unknown-linux-gnu";
    let rig = Rig::new("human-releases");
    rig.publish_head(&Doc::new(120, &[("ay", 14327)]).overlay(LINUX, &[("ay", 14328)]));
    for build in [14327, 14328] {
        let mut pack = rig.pack("ay", build, &[MAC, LINUX]);
        let mf = format!("pkg-ay-{build}.toml");
        let version = "1.20261109.1-dev.2+upstream.0.27.0";
        let raw = String::from_utf8(pack.files.iter().find(|(n, _)| n == &mf).unwrap().1.clone())
            .unwrap()
            .replace(&format!("0.1.{build}"), version);
        for (name, bytes) in &mut pack.files {
            if name == &mf {
                *bytes = raw.as_bytes().to_vec();
            }
            if name == &format!("{mf}.sig") {
                *bytes = rig.keys.sign(raw.as_bytes());
            }
        }
        let slug = rig.ctx.public_slug("ay");
        for (name, bytes) in pack.files {
            rig.host.put_asset(&slug, &pack.tag, &name, bytes);
        }
        let mut release = rig.host.release_of(&slug, &pack.tag).unwrap();
        release.published_at = Some("2026-11-10T01:29:49Z".into());
        rig.host.put(&slug, &pack.tag, release);
    }
    let rows = status::release_lines(&rig.ctx, None, &["ay".into()]).unwrap();
    let text = rows.join("\n");
    assert!(
        text.contains("ay | 1.20261109.1-dev.2+upstream.0.27.0 | 2026-11-10T01:29:49Z"),
        "{text}"
    );
    assert!(
        text.contains("Installation verification: NOT CHECKED"),
        "{text}"
    );
    assert_eq!(
        rows.iter().filter(|r| r.starts_with("ay |")).count(),
        2,
        "{text}"
    );
    assert!(
        text.contains("channel stable; build 14327; index 120"),
        "{text}"
    );
    assert!(
        text.contains("channel stable; build 14328; index 120"),
        "{text}"
    );
    assert!(text.contains("| aarch64-apple-darwin | Public release metadata; payload not checked\n  program ay; channel stable; build 14327;"), "{text}");
    assert!(text.contains("| x86_64-unknown-linux-gnu | Public release metadata; payload not checked\n  program ay; channel stable; build 14328;"), "{text}");
    assert!(
        !rig.host.calls().iter().any(|c| c.contains(".tar.zst")),
        "a report must not download or probe payloads"
    );
}

#[test]
fn release_report_never_invents_a_date_or_accepts_a_foreign_signed_manifest() {
    let rig = Rig::new("human-release-unknown");
    rig.publish_head(&Doc::new(120, &[("ay", 14327)]));
    let pack = rig.lay_pack("alabsystems", "ay", 14327, &["aarch64-apple-darwin"]);
    for date in [None, Some("not-a-date")] {
        let slug = rig.ctx.public_slug("ay");
        let mut release = rig.host.release_of(&slug, &pack.tag).unwrap();
        release.published_at = date.map(str::to_string);
        rig.host.put(&slug, &pack.tag, release);
        let text = status::release_lines(&rig.ctx, None, &[])
            .unwrap()
            .join("\n");
        assert!(
            text.contains("ay | 0.1.14327 | UNKNOWN | aarch64-apple-darwin"),
            "{text}"
        );
    }
    let slug = rig.ctx.public_slug("ay");
    for (program, build) in [("ay", 14328), ("mc", 14327)] {
        let other = rig.pack(program, build, &["aarch64-apple-darwin"]);
        for (name, bytes) in other.files {
            if name.starts_with("pkg-") {
                rig.host.put_asset(
                    &slug,
                    &pack.tag,
                    &name.replace(&format!("{program}-{build}"), "ay-14327"),
                    bytes,
                );
            }
        }
        assert!(status::release_lines(&rig.ctx, None, &[]).is_err());
    }
}

#[test]
fn report_names_codex_alab_and_keeps_carried_vendor_pins_distinct() {
    let rig = Rig::new("human-codex-vendor");
    rig.publish_head(&Doc::new(120, &[("codex", 2026110901), ("claude", 1)]));
    rig.lay_pack(
        "alabsystems",
        "codex",
        2026110901,
        &["aarch64-apple-darwin"],
    );
    let text = status::release_lines(&rig.ctx, None, &[])
        .unwrap()
        .join("\n");
    assert!(
        text.contains("codex-alab | 0.1.2026110901 | UNKNOWN | aarch64-apple-darwin"),
        "{text}"
    );
    assert!(
        text.contains("claude | UNKNOWN | UNKNOWN | UNKNOWN | Vendor-direct"),
        "{text}"
    );
    assert!(!rig.host.calls().iter().any(|c| c.contains("atpkg-claude-")));
}

//! The seed pin, at publish time: a trust pack is published only once the trust repo's
//! origin main contains the re-pin its SEED-MINT names, pins this compiler through it
//! (`src/stage0`'s `compiler_git_commit_hash`, and the generated section byte for byte),
//! its seed ledger names the re-pin's archive release, and that release exists.
//!
//! One refusal per line, collected by the `rustc` group's preflight. The receipt itself is
//! checked by `atpkg::lineage::seed_mint_refusals`.

use std::path::Path;
use std::time::{Duration, Instant};

use crate::ctx::Ctx;
use crate::host::{HostError, Slug};

/// The trust repo's seed ledger, at its origin main.
pub const LEDGER: &str = "bootstrap/trust-stage0/seed-ledger.toml";

/// The line `prepare.py`'s section of `src/stage0` starts with: from it to the end are
/// the pins it wrote.
pub const GENERATED_MARKER: &str =
    "# The section below was generated by src/tools/trust-stage0-dist/prepare.py";

/// The bound on one network step (a hang detector).
pub const NETWORK_BOUND: Duration = Duration::from_secs(60);

/// The rest of the first line of `text` that starts with `<key>=`.
#[must_use]
pub fn field(text: &str, key: &str) -> Option<String> {
    let prefix = format!("{key}=");
    text.lines()
        .find_map(|l| l.strip_prefix(&prefix))
        .map(str::to_string)
}

/// `prepare.py`'s section of a `src/stage0`: from its marker line to the end.
#[must_use]
pub fn generated_section(stage0: &str) -> String {
    stage0
        .split_inclusive('\n')
        .skip_while(|l| !l.starts_with(GENERATED_MARKER))
        .collect()
}

/// The one-line account of a receipt the group's transcript prints.
#[must_use]
pub fn describe(receipt: &str) -> String {
    let f = |k: &str| field(receipt, k).unwrap_or_default();
    let short = |k: &str| f(k).chars().take(10).collect::<String>();
    let relation = f("ddc_seed_relation");
    let kind = if relation == "lineage-disjoint" {
        "diverse"
    } else {
        "not diverse"
    };
    format!(
        "built from the pin {}; double compile against {} ({} lineage, {relation}: {kind}): \
         both stage2 trees {}; latest lineage-disjoint cut {}; re-pin {} ({}), archives {}",
        short("pinned_seed_commit"),
        short("ddc_seed_commit"),
        f("ddc_seed_lineage"),
        f("stage2_tree_sha256_pinned_seed"),
        short("lineage_disjoint_anchor"),
        short("repin_commit"),
        f("repin_branch"),
        f("repin_release_tag"),
    )
}

/// `git -C <dir> <args…>` within [`NETWORK_BOUND`]: its stdout, or why not.
fn git(dir: &Path, args: &[&str]) -> Result<String, String> {
    let mut cmd = aterm_uds::spawnfd::command("git");
    cmd.arg("-C")
        .arg(dir)
        .args(args)
        .env("GIT_TERMINAL_PROMPT", "0");
    match aterm_uds::deadline::output_until(&mut cmd, Instant::now() + NETWORK_BOUND) {
        Ok(out) if out.status.success() => Ok(String::from_utf8_lossy(&out.stdout).into_owned()),
        Ok(out) => Err(String::from_utf8_lossy(&out.stderr)
            .lines()
            .find(|l| !l.trim().is_empty())
            .unwrap_or("git failed")
            .to_string()),
        Err(e) => Err(format!("{e:?}")),
    }
}

/// Why the seal's trust pack may not be published yet: one refusal per entry, none when
/// `trust_repo`'s origin main carries this cut's re-pin, pins this compiler through it,
/// and its ledger's archive release exists (asked of the staging identity's host). One
/// `git fetch origin main`, bounded.
#[must_use]
pub fn publish_refusals(ctx: &Ctx, trust_repo: &Path, seal: &Path) -> Vec<String> {
    let repo = ctx.shown(trust_repo);
    let receipt =
        std::fs::read_to_string(seal.join(atpkg::lineage::SEED_MINT_FILE)).unwrap_or_default();
    let repin = field(&receipt, "repin_commit").unwrap_or_default();
    let tag = field(&receipt, "repin_release_tag").unwrap_or_default();
    let commit = field(&receipt, "repin_compiler_git_commit_hash").unwrap_or_default();
    if let Err(why) = git(trust_repo, &["fetch", "-q", "origin", "main"]) {
        return vec![format!(
            "cannot fetch {repo}'s origin main ({why}), so nothing says main pins this seal's \
             compiler"
        )];
    }
    if repin.is_empty()
        || git(
            trust_repo,
            &["merge-base", "--is-ancestor", &repin, "FETCH_HEAD"],
        )
        .is_err()
    {
        return vec![format!(
            "{repo}'s origin main does not contain this cut's re-pin commit {}. Publish its \
             archives as release {tag}, land the re-pin, then publish this pack: a pack whose \
             re-pin main does not carry is how the pin and the pack drift (another machine's \
             cut of the same commit carries other bytes)",
            if repin.is_empty() { "<none>" } else { &repin }
        )];
    }
    let main_stage0 = git(trust_repo, &["show", "FETCH_HEAD:src/stage0"]).unwrap_or_default();
    let repin_stage0 =
        git(trust_repo, &["show", &format!("{repin}:src/stage0")]).unwrap_or_default();
    let pinned = field(&main_stage0, "compiler_git_commit_hash").unwrap_or_default();
    let short: String = repin.chars().take(10).collect();
    if pinned != commit {
        return vec![format!(
            "{repo}'s origin main contains the re-pin {short} but pins {pinned} in src/stage0, \
             not this seal's compiler {commit}: a later re-pin superseded this cut"
        )];
    }
    let mut refusals = Vec::new();
    let generated = generated_section(&repin_stage0);
    if generated.is_empty() || generated_section(&main_stage0) != generated {
        refusals.push(format!(
            "the generated section of src/stage0 on {repo}'s origin main is not the re-pin \
             {short}'s: main pins this compiler through other archives than the ones this cut \
             minted"
        ));
    }
    let ledger = git(trust_repo, &["show", &format!("FETCH_HEAD:{LEDGER}")]).unwrap_or_default();
    let release = ledger.parse::<aterm_toml::Table>().ok().and_then(|t| {
        let r = t.get("release")?;
        let repo = r.get("repo")?.as_str()?.to_string();
        let tag = r.get("tag")?.as_str()?.to_string();
        Some((repo, tag))
    });
    match release {
        Some((owner_repo, ledger_tag)) if ledger_tag == tag => {
            let slug = match owner_repo.split_once('/') {
                Some((o, r)) => Slug::new(o, r),
                None => Slug::new(owner_repo.as_str(), ""),
            };
            match ctx.hosts.staging.release(&slug, &tag) {
                Ok(_) => {}
                Err(HostError::NotFound) => refusals.push(format!(
                    "the seed archives are not published: release {tag} on {owner_repo} does not \
                     exist, so a fresh checkout of main cannot fetch the pin it builds from. \
                     Upload the re-pin's dist/*.tar.xz there first"
                )),
                Err(e) => refusals.push(format!(
                    "could not ask whether the seed archives' release {tag} on {owner_repo} \
                     exists ({e}) — nothing shows a fresh checkout can fetch its pin"
                )),
            }
        }
        other => refusals.push(format!(
            "the seed ledger on {repo}'s origin main names release '{}', not this cut's {tag}",
            other.map_or_else(|| "<none>".to_string(), |(r, t)| format!("{r} {t}"))
        )),
    }
    refusals
}

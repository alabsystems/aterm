/// The first line of every index the retired shell publisher, `tools/atpkg-index.sh`, rendered.
pub const SHELL_HEAD_LINE: &str = "# Auto-generated by tools/atpkg-index.sh";

/// Which writer rendered an index, as its signed first line says.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Producer {
    /// `atpkg-publish index` ([`super::index::HEAD_LINE`]).
    Publisher,
    /// The retired shell publisher, `tools/atpkg-index.sh` ([`SHELL_HEAD_LINE`]).
    RetiredShell,
    /// A first line neither writes.
    Unknown(String),
}

impl Producer {
    /// The producer of an index whose first line is `head_line`.
    #[must_use]
    pub fn of(head_line: &str) -> Self {
        if head_line == super::index::HEAD_LINE {
            Self::Publisher
        } else if head_line.starts_with(SHELL_HEAD_LINE) {
            Self::RetiredShell
        } else {
            Self::Unknown(head_line.to_string())
        }
    }

    /// Its status line.
    #[must_use]
    pub fn line(&self) -> String {
        match self {
            Self::Publisher => "producer: atpkg-publish index".to_string(),
            Self::RetiredShell => "producer: tools/atpkg-index.sh — RETIRED SHELL PUBLISHER: a \
                                   machine still runs the shell lane, which keeps none of \
                                   `atpkg-publish index`'s refusals and writes every repo from \
                                   its old spec. Clients refuse a successor that lowers a pin \
                                   or moves a repo under the same build (atpkg::succession), \
                                   but this head stands as signed: disarm that lane, then \
                                   publish the next index with `atpkg-publish index`"
                .to_string(),
            Self::Unknown(line) => format!(
                "producer: unknown — the first line {line:?} is neither `atpkg-publish index`'s \
                 nor the retired shell publisher's"
            ),
        }
    }
}

/// The status lines of a verified quad at `now_unix`.
#[must_use]
pub fn describe(quad: &VerifiedQuad, now_unix: i64) -> Vec<String> {
    let index = &quad.index;
    let lapsed = if quad.lapsed(now_unix) {
        " — LAPSED: every client refuses this index; re-sign it (atpkg-publish index \
         --valid-until <future> --upload)"
    } else {
        ""
    };
    let mut out = vec![
        format!(
            "atpkg-index-{} — signed by machine {} under roster_seq {}",
            index.index_build,
            index.attribution().machine_id,
            index.roster_seq()
        ),
        Producer::of(&quad.head_line).line(),
        format!(
            "horizon: index {}, roster {}{lapsed}",
            index.valid_until, quad.roster.valid_until
        ),
    ];
    for c in &index.channels {
        out.push(format!(
            "channel {} (channel_build {}): min_build {}",
            c.name, c.channel_build, c.min_build
        ));
        for (p, floor) in &c.min_build_by_program {
            out.push(format!("  min_build {p}: {floor}"));
        }
        if !c.yanked.is_empty() {
            out.push(format!("  yanked: {}", c.yanked.join(" ")));
        }
        let order: Vec<&str> = programs::PROGRAMS
            .iter()
            .map(|d| d.name)
            .filter(|n| c.pin.contains_key(*n))
            .chain(
                c.pin
                    .keys()
                    .map(String::as_str)
                    .filter(|n| programs::get(n).is_none()),
            )
            .collect();
        for p in order {
            let group = index
                .programs
                .get(p)
                .and_then(|b| b.coherence_group.as_deref())
                .map(|g| format!(" [{g}]"))
                .unwrap_or_default();
            out.push(format!("  pin {p} = {}{group}", c.pin[p]));
        }
        for (t, cells) in &c.pin_by_target {
            let known = if Triple::parse(t).is_ok() {
                ""
            } else {
                " (not a target this client knows)"
            };
            for (p, b) in cells {
                out.push(format!("  pin {p} = {b} on {t}{known}"));
            }
        }
    }
    for (name, block) in &index.programs {
        match programs::get(name) {
            None if atpkg::vendor_direct::is_vendor(name) => out.push(format!(
                "[programs.{name}] is vendor-direct: no publish pins it, and --retire {name} \
                 drops it"
            )),
            None => out.push(format!(
                "drift: [programs.{name}] is in the index but not a row of programs::PROGRAMS"
            )),
            Some(def) if programs::alab_package(name).is_some() && block.repo != def.repo => {
                out.push(format!(
                    "[programs.{name}] names repo {:?}, not ALab's {:?}: carried as it stands, \
                     and every client keeps {name} on its vendor lane, until `index --pin \
                     {name}=<b>` names a verified {} pack",
                    block.repo, def.repo, def.repo
                ));
            }
            Some(def) => {
                let mut drift = Vec::new();
                if block.repo != def.repo {
                    drift.push(format!("repo {:?} (table {:?})", block.repo, def.repo));
                }
                if block.policy != programs::POLICY {
                    drift.push(format!(
                        "policy {:?} (table {:?})",
                        block.policy,
                        programs::POLICY
                    ));
                }
                if block.coherence_group.as_deref() != def.group {
                    drift.push(format!(
                        "coherence_group {:?} (table {:?})",
                        block.coherence_group, def.group
                    ));
                }
                if block.system.as_deref() != def.system {
                    drift.push(format!(
                        "system {:?} (table {:?})",
                        block.system, def.system
                    ));
                }
                if block.unavailable_hint.as_deref() != def.unavailable_hint {
                    drift.push(format!(
                        "unavailable_hint {:?} (table {:?})",
                        block.unavailable_hint, def.unavailable_hint
                    ));
                }
                if !drift.is_empty() {
                    out.push(format!(
                        "drift: [programs.{name}] {} — the next publish renders the table's",
                        drift.join(", ")
                    ));
                }
            }
        }
    }
    out
}

/// `atpkg-publish status [--quad DIR] [--releases [PRODUCT…]]`.
/// # Errors
/// A usage error for a bad command line; a refusal when the quad does not verify; a could-not-run
/// when the channel cannot be read.
pub fn run(ctx: &Ctx, args: &[String]) -> Result<()> {
    let mut dir: Option<PathBuf> = None;
    let mut releases = false;
    let mut products = Vec::new();
    let mut i = 0;
    while i < args.len() {
        match args[i].as_str() {
            "--quad" => dir = Some(PathBuf::from(flag_value(args, &mut i, "--quad")?)),
            "--releases" => releases = true,
            product if releases && !product.starts_with('-') => products.push(product.to_string()),
            other => {
                return Err(Error::usage(format!(
                    "status: unknown argument `{other}` (status [--quad DIR] [--releases [PRODUCT…]])"
                )));
            }
        }
        i += 1;
    }
    let mut log = Log::echo("atpkg-publish status");
    let output = if releases {
        release_lines(ctx, dir.as_deref(), &products)?
    } else {
        lines(ctx, dir.as_deref())?
    };
    for line in output {
        if line == Producer::RetiredShell.line() {
            log.warn(line);
        } else {
            log.say(line);
        }
    }
    Ok(())
}

/// The status of the channel head ([`describe`]).
/// # Errors
/// A refusal when the quad does not verify; a could-not-run when the channel cannot be read.
pub fn lines(ctx: &Ctx, dir: Option<&Path>) -> Result<Vec<String>> {
    Ok(describe(&read_quad(ctx, dir)?, ctx.now_unix))
}

fn read_quad(ctx: &Ctx, dir: Option<&Path>) -> Result<VerifiedQuad> {
    match dir {
        Some(d) => quad::verify_dir_with(ctx, d, Freshness::Ignore),
        None => {
            let scratch = Scratch::new("status")?;
            let (_, q) =
                quad::fetch_head_with(ctx, &ctx.index_slug(), scratch.path(), Freshness::Ignore)?;
            Ok(q)
        }
    }
}

/// Human release rows selected by the signed channel, optionally limited to `products`.
/// Versions come from signed package manifests, dates from the host's `published_at`.
/// Only metadata is read: neither payload nor local installation verification is implied.
/// An empty product list reports all pins; target overlays use the client's own channel view.
///
/// # Errors
/// A refusal for invalid signatures or a manifest for a different product/build; a
/// could-not-run when public metadata cannot be read. Unknown dates remain `UNKNOWN`.
pub fn release_lines(ctx: &Ctx, dir: Option<&Path>, products: &[String]) -> Result<Vec<String>> {
    let quad = read_quad(ctx, dir)?;
    let selected: std::collections::BTreeSet<_> = quad
        .index
        .channels
        .iter()
        .flat_map(crate::pins::union)
        .filter(|(p, _)| products.is_empty() || products.contains(p))
        .collect();
    for product in products {
        if !selected.iter().any(|(p, _)| p == product) {
            return Err(Error::usage(format!(
                "status: `{product}` has no signed channel pin"
            )));
        }
    }
    let scratch = Scratch::new("release-report")?;
    let mut out = vec![
        "Product | public version | published UTC | platform | status".to_string(),
        "Installation verification: NOT CHECKED (use `aterm pkg verify PRODUCT`). Payloads are not checked by this report.".to_string(),
    ];
    if quad.lapsed(ctx.now_unix) {
        out.push("LAPSED index: these are historical pins; clients refuse this index.".to_string());
    }
    for (product, build) in selected {
        let repo = quad.index.programs.get(&product).ok_or_else(|| {
            Error::refused(format!("status: pin `{product}` names no repository"))
        })?;
        let agent = atpkg::alab::agent(&product).filter(|a| a.repo == repo.repo);
        if atpkg::vendor_direct::is_vendor(&product) && agent.is_none() {
            out.push(format!(
                "{product} | UNKNOWN | UNKNOWN | UNKNOWN | Vendor-direct; carried pin is not an ALab package release"
            ));
            out.push(format!("  build {build}; index {}", quad.index.index_build));
            continue;
        }
        let name = agent.map_or(product.as_str(), |a| a.product);
        let slug = ctx.public_slug(&repo.repo);
        let tag = upload::tag(&product, build);
        let work = scratch.path().join(&tag);
        let manifest = pkgdoc::manifest_name(&product, build);
        let signature = pkgdoc::sig_name(&product, build);
        let mut pair = Vec::new();
        for name in [&manifest, &signature] {
            let path = work.join(name);
            match ctx
                .hosts
                .channel
                .fetch_public(&slug, &tag, name, &path, atpkg::net::MANIFEST_CAP)
            {
                Probe::Present => {}
                Probe::Absent => {
                    return Err(Error::cannot_run(format!(
                        "status: public metadata {slug}@{tag}/{name} is absent"
                    )));
                }
                Probe::Unknown(why) => {
                    return Err(Error::cannot_run(format!(
                        "status: public metadata {slug}@{tag}/{name} could not be read: {why}"
                    )));
                }
            }
            pair.push(
                crate::identity::read_regular_bytes(&path, atpkg::net::MANIFEST_CAP)
                    .map_err(|e| Error::io("read public package metadata", &e))?,
            );
        }
        let pkg = quad.verify_pkg(&pair[0], &pair[1])?;
        if pkg.program != product || pkg.build_number != build {
            return Err(Error::refused(format!(
                "status: {slug}@{tag} signed metadata names {} build {}, expected {product} build {build}",
                pkg.program, pkg.build_number
            )));
        }
        let release = ctx.hosts.channel.release(&slug, &tag).ok();
        let observed = release.as_ref().filter(|r| r.tag == tag && !r.draft);
        let date = observed
            .and_then(|r| r.published_at.as_deref())
            .filter(|s| aterm_types::rfc3339::parse_utc(s).is_some())
            .unwrap_or("UNKNOWN");
        let version = if pkg.version.is_empty() {
            "UNKNOWN"
        } else {
            &pkg.version
        };
        for channel in &quad.index.channels {
            for artifact in &pkg.artifacts {
                let view = channel.for_target(&artifact.target);
                if view.pin.get(&product) != Some(&build) {
                    continue;
                }
                let status = if atpkg::gate::is_yanked(&view, &product, build) {
                    "YANKED"
                } else if build < view.min_build_for(&product) {
                    "BELOW FLOOR"
                } else if observed.is_some_and(|r| r.assets.contains(&artifact.asset)) {
                    "Public release metadata; payload not checked"
                } else {
                    "Signed metadata public; payload publication UNKNOWN"
                };
                out.push(format!(
                    "{name} | {version} | {date} | {} | {status}",
                    artifact.target
                ));
                out.push(format!(
                    "  program {product}; channel {}; build {build}; index {}",
                    channel.name, quad.index.index_build
                ));
            }
        }
    }
    Ok(out)
}

//! First-party Wayland for aterm: the protocol tables, generated from the
//! protocol descriptions, and a runtime over libwayland-client.
//!
//! It replaces wayland-client, wayland-backend, wayland-sys,
//! wayland-scanner, wayland-protocols and their helpers on Linux
//! (docs/AUDIT-third-party-2026-10-15.md, linux-windowing LW.6). The C
//! library stays: wgpu's Vulkan WSI and aterm's EGL surfaces take a real
//! `wl_display *` / `wl_surface *`, so this crate drives the system's
//! libwayland-client, opened at run time through `aterm-dl`, on the
//! display winit connected.
//!
//! * [`iface`]: `struct wl_interface` / `struct wl_message` as statics.
//! * [`protocols`]: generated by `src/bin/wayland-scan` from `protocols/`
//!   (the core protocol, xdg-shell, xdg-decoration, xdg-activation,
//!   viewporter, fractional-scale, cursor-shape, text-input-v3 and
//!   primary-selection): each interface's table, opcodes, enums and one
//!   `unsafe fn` per request. Held to wayland-scanner 0.31.10's tables by
//!   `tests/recorded/`, recorded once by `tests/recorder` (a crate outside
//!   the workspace).
//! * [`proxy`]: proxies, private event queues, marshalling, and one
//!   dispatcher that decodes each event by its signature for a closure.
//! * [`globals`]: the registry and its globals on a private queue.
//! * [`output`]: every output, its geometry, modes, scale and name.
//! * [`xdg`]: the xdg-shell toplevel, its configure sequence and the
//!   negotiated decoration mode.
//! * [`cursor`]: aterm's pointer shapes as cursor-shape-v1 shapes and as
//!   themed images through libwayland-cursor.
//! * [`seat`]: every seat and the pointer, keyboard and touch its
//!   capabilities announce, their events decoded in order (a pointer's
//!   grouped by frame, [`pointer_frame`]; a keyboard's keymap read), and the
//!   serials and focus a selection or a drag needs.
//! * [`selection`]: the clipboard and drag-and-drop (`wl_data_device`) and
//!   the primary selection, their offers and sources, and pipe I/O.
//! * [`sink`]: where the seats' and the selections' events go, in the order
//!   the queue dispatched them.

pub mod cursor;
pub mod globals;
pub mod iface;
pub mod output;
pub mod pointer_frame;
pub mod protocols;
pub mod proxy;
#[cfg(unix)]
pub mod seat;
#[cfg(unix)]
pub mod selection;
pub mod sink;
pub mod sys;
pub mod xdg;

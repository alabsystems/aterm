/// A LANDING AFTER A RESTATED RESOLUTION NAMES NO RULE THAT DID NOT RUN FOR IT: a resolved
/// merge landed restated (a new commit of its tree and parents), and the checkout stayed on
/// the resolved merge, as where its move to the landing failed. A further change from there
/// lands with a message that names no rule: the one that ran did so for the landing main
/// holds. NEGATIVE CONTROL: without [`Git::restated`] the second landing copies the first's

/// Where a crate's spec table sits in the worlds below.
const SPEC: &str = "crates/a/SPECS.md";

/// A `SPECS.md` stating `counts`, with its spec table's rows `specs` and its test table's rows
/// `tests` (each a header row first), and where `notes`, a third, empty table.
fn spec(counts: (usize, usize), specs: &[&str], tests: &[&str], notes: bool) -> String {
    let table = |rows: &[&str]| format!("```tsv\n{}\n```\n", rows.join("\n"));
    format!(
        "# a: specs\n\nResult: **{} specs**, sampled by **{} tests** (§2).\n\n## 1. Specs\n\n{}\n\
         ## 2. Tests\n\n{}{}",
        counts.0,
        counts.1,
        table(specs),
        table(tests),
        if notes {
            "\n## 3. Notes\n\n```tsv\n```\n"
        } else {
            ""
        }
    )
}

/// The spec table's header and the test table's.
const SPEC_HEAD: &str = "id\tkind\tstatement";
const TEST_HEAD: &str = "file\ttest\tprimary";

/// A world whose `SPECS.md` both sides changed: the branch edited `r1` (or `branch_r1`) and
/// added `r3` and its test, main edited `r2` (and `main_r1`) and added `r4` and its test, and
/// each set the counts to 3 and 3. The world and main's new tip.
fn spec_world(notes: bool, branch_r1: &str, main_r1: &str) -> (World, String) {
    let base = spec(
        (2, 2),
        &[SPEC_HEAD, "r1\tfn\tbase one", "r2\tfn\tbase two"],
        &[TEST_HEAD, "f.rs\tt1\tr1", "f.rs\tt2\tr2"],
        notes,
    );
    let ours = spec(
        (3, 3),
        &[
            SPEC_HEAD,
            branch_r1,
            "r2\tfn\tbase two",
            "r3\tfn\tbranch three",
        ],
        &[TEST_HEAD, "f.rs\tt1\tr1", "f.rs\tt2\tr2", "f.rs\tt3\tr3"],
        notes,
    );
    let theirs = spec(
        (3, 3),
        &[SPEC_HEAD, main_r1, "r2\tfn\tmain two", "r4\tfn\tmain four"],
        &[TEST_HEAD, "f.rs\tt1\tr1", "f.rs\tt2\tr2", "f.rs\tt4\tr4"],
        notes,
    );
    let world = world();
    seed_main(&world, &[(SPEC, base.as_str())]);
    commit(&world.work, SPEC, &ours);
    let moved = rival_moves(&world, SPEC, &theirs);
    (world, moved)
}

/// A SPEC TABLE CONFLICT TAKES EACH ROW'S CHANGED SIDE AND RECOUNTS: each side changed one row
/// of the spec table and added one to each table. The landed file holds the branch's edit and
/// main's, main's added rows in main's order and the branch's after them, and counts main's
/// stated numbers moved by the rows each table gained (4 and 4). The test table's first column
/// repeats, so its rows are keyed by file and test. CONTROL: with a third table the counts line
/// is plain text, which both sides set alike, so it lands as they wrote it (3 and 3).
#[test]
fn a_spec_table_conflict_takes_each_rows_changed_side_and_recounts() {
    for notes in [false, true] {
        let (world, _) = spec_world(notes, "r1\tfn\tbranch one", "r1\tfn\tbase one");
        let (code, said, bases) = land_with(&world, crates(&["a"]), Lane::Pass, |_, _| green());
        assert_eq!((code, bases.len()), (exit::PASS, 1), "{said:#?}");
        assert!(
            said.iter()
                .any(|line| line.contains("resolved by rule: spec-table-rows")),
            "{said:#?}"
        );
        let counted = if notes { (3, 3) } else { (4, 4) };
        let expected = spec(
            counted,
            &[
                SPEC_HEAD,
                "r1\tfn\tbranch one",
                "r2\tfn\tmain two",
                "r4\tfn\tmain four",
                "r3\tfn\tbranch three",
            ],
            &[
                TEST_HEAD,
                "f.rs\tt1\tr1",
                "f.rs\tt2\tr2",
                "f.rs\tt4\tr4",
                "f.rs\tt3\tr3",
            ],
            notes,
        );
        let landing = origin_main(&world);
        assert_eq!(
            git(&world.work, &["show", &format!("{landing}:{SPEC}")]),
            expected.trim_end(),
            "notes table: {notes}"
        );
    }
}

/// A SPEC ROW BOTH SIDES CHANGED DIFFERENTLY RESOLVES NOTHING: the merge is left for the
/// person, conflicted, and the line names the row. CONTROL:
/// [`a_spec_table_conflict_takes_each_rows_changed_side_and_recounts`], where one side left
/// that row alone.
#[test]
fn a_spec_row_both_sides_changed_differently_resolves_nothing() {
    let (world, moved) = spec_world(false, "r1\tfn\tbranch one", "r1\tfn\tmain one");
    let (code, said, bases) = land_with(&world, crates(&["a"]), Lane::Pass, |_, _| green());
    assert_eq!((code, bases.len()), (exit::CONFLICT, 0), "{said:#?}");
    assert_eq!(origin_main(&world), moved, "a conflict pushes nothing");
    assert!(
        git(&world.work, &["status", "--porcelain"]).contains(&format!("UU {SPEC}")),
        "{said:#?}"
    );
    assert!(
        said.iter()
            .any(|line| line.contains("row `r1` changed differently on both sides")),
        "{said:#?}"
    );
}

/// A SPEC TABLE'S KEY OF ONE OR TWO COLUMNS MUST BE UNIQUE, and the rule refuses what it
/// cannot carry over whole. A table keyed by file and test (its first column repeats) merges
/// both sides' rows; one whose rows repeat their first two cells, prose both sides edited, and
/// a branch that only reordered rows are each refused.
#[test]
fn a_spec_key_of_one_or_two_columns_must_be_unique() {
    let table = |prose: &str, rows: &[&str]| {
        format!("# T\n\n{prose}\n\n```tsv\n{}\n```\n", rows.join("\n"))
    };
    let base = table("prose", &["file\ttest", "f\tt1", "f\tt2"]);
    let ours = table("prose", &["file\ttest", "f\tt1", "f\tt2", "f\tt3"]);
    let theirs = table("prose", &["file\ttest", "f\tt1", "f\tt2", "f\tt4"]);
    let (merged, _) = resolve::spec_table(&base, &ours, &theirs).expect("keyed by file and test");
    assert_eq!(
        merged,
        table("prose", &["file\ttest", "f\tt1", "f\tt2", "f\tt4", "f\tt3"])
    );

    let repeated = |last: &str| table("prose", &["file\ttest\tx", "f\tt1\ta", "f\tt1\tb", last]);
    let refused = resolve::spec_table(
        &repeated("f\tt2\tc"),
        &repeated("f\tt2\tours"),
        &repeated("f\tt2\ttheirs"),
    )
    .unwrap_err();
    assert!(
        refused.contains("no key of one or two columns is unique"),
        "{refused}"
    );

    let refused = resolve::spec_table(
        &base,
        &table("branch prose", &["file\ttest", "f\tt1", "f\tt2", "f\tt3"]),
        &table("main prose", &["file\ttest", "f\tt1", "f\tt2", "f\tt4"]),
    )
    .unwrap_err();
    assert!(refused.contains("outside the tables"), "{refused}");

    let refused = resolve::spec_table(
        &base,
        &table("prose", &["file\ttest", "f\tt2", "f\tt1"]),
        &theirs,
    )
    .unwrap_err();
    assert!(refused.contains("reordered"), "{refused}");
}

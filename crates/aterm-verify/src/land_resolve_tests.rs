//! A merge conflict in `verify land`: the mechanical rules that resolve one whose every path has
//! a rule ([`resolve`]), the resolved merge judged in full, and the exit of its own that tells a
//! conflict no rule resolves from a red.

use super::*;

/// The line `goals.py repo-docs` heads `docs/PLAN.md` and `docs/STATUS.md` with on main.
const GENERATED_LINE: &str = "Generated from the lab tracker (the publication repo, goals/data) \
                              by `goals.py repo-docs aterm`. Do not edit this file: change the \
                              tracker and regenerate.";

/// Move origin's main from the rival clone by one commit holding every file of `files`. The new
/// tip.
fn rival_moves_files(world: &World, files: &[(&str, &str)]) -> String {
    git(&world.rival, &["fetch", "-q", "origin"]);
    git(
        &world.rival,
        &["checkout", "-q", "-B", "main", "origin/main"],
    );
    for (file, text) in files {
        write(&world.rival, file, text);
    }
    git(&world.rival, &["add", "-A"]);
    git(&world.rival, &["commit", "-q", "-m", "main moves"]);
    git(&world.rival, &["push", "-q", "origin", "main"]);
    git(&world.rival, &["rev-parse", "HEAD"])
}

/// Put `files` on main and bring the branch up to it: the merge base both sides then change.
fn seed_main(world: &World, files: &[(&str, &str)]) {
    rival_moves_files(world, files);
    git(&world.work, &["fetch", "-q", "origin"]);
    git(&world.work, &["merge", "-q", "--ff-only", "origin/main"]);
}

/// Commit every file of `files` on the branch: the commit.
fn commit_files(world: &World, files: &[(&str, &str)]) -> String {
    for (file, text) in files {
        write(&world.work, file, text);
    }
    git(&world.work, &["add", "-A"]);
    git(&world.work, &["commit", "-q", "-m", "branch edits"]);
    git(&world.work, &["rev-parse", "HEAD"])
}

/// The message of commit `at`.
fn message(world: &World, at: &str) -> String {
    git(&world.work, &["log", "-1", "--format=%B", at])
}

/// A tracker document's text: its heading, main's generated line where `generated`, and one
/// package row in `state`.
fn tracker_doc(heading: &str, generated: bool, state: &str) -> String {
    let line = if generated {
        GENERATED_LINE
    } else {
        "Written by hand."
    };
    format!("# {heading}\n\n{line}\n\n| X-1 | {state} |\n")
}

/// `docs/PLAN.md` and `docs/STATUS.md` as the tracker generates them, each package in `state`.
fn tracker_docs(state: &str) -> Vec<(&'static str, String)> {
    [("docs/PLAN.md", "Plan"), ("docs/STATUS.md", "Status")]
        .into_iter()
        .map(|(file, heading)| (file, tracker_doc(heading, true, state)))
        .collect()
}

/// `files` as the path and text pairs the world's helpers take.
fn borrowed<'a>(files: &'a [(&'static str, String)]) -> Vec<(&'static str, &'a str)> {
    files
        .iter()
        .map(|(file, text)| (*file, text.as_str()))
        .collect()
}

/// A world whose branch and main each changed the package row of `docs/PLAN.md` and
/// `docs/STATUS.md` (with `branch`'s and `main`'s further files): git's merge conflicts in both.
/// The world and main's new tip.
fn tracker_world(branch: &[(&str, &str)], main: &[(&str, &str)]) -> (World, String) {
    let world = world();
    seed_main(&world, &borrowed(&tracker_docs("ready")));
    let ours = tracker_docs("running");
    let mut mine: Vec<(&str, &str)> = borrowed(&ours);
    mine.extend_from_slice(branch);
    commit_files(&world, &mine);
    let theirs = tracker_docs("done");
    let mut moving: Vec<(&str, &str)> = borrowed(&theirs);
    moving.extend_from_slice(main);
    let moved = rival_moves_files(&world, &moving);
    (world, moved)
}

/// A CONFLICT IN A TRACKER-GENERATED DOCUMENT TAKES MAIN'S SIDE: `docs/PLAN.md` and
/// `docs/STATUS.md`, which `goals.py repo-docs` regenerates, conflict and land as main's
/// copies, judged, the landing naming the rule. Where main moves again during the judgment and
/// the pass composes onto it, the composed landing names the rule too ([`Git::resolutions`]).
/// CONTROLS: the same conflict in `docs/PLANS.md`, which no rule covers, and in a
/// `docs/PLAN.md` whose main copy does not say it is generated, each stop with
/// [`exit::CONFLICT`] and push nothing.
/// NEGATIVE CONTROL: with no rule the first landing exits [`exit::CONFLICT`].
#[test]
fn a_conflict_in_a_tracker_generated_document_takes_mains_side() {
    let (world, moved) = tracker_world(&[], &[]);
    let (code, said, bases) = land_with(&world, crates(&["a"]), |_, _| green());
    assert_eq!((code, bases.len()), (exit::PASS, 1), "{said:#?}");
    assert_eq!(
        bases,
        std::slice::from_ref(&moved),
        "the resolved merge was judged: {said:#?}"
    );
    let landing = origin_main(&world);
    for (file, text) in &tracker_docs("done") {
        assert_eq!(
            git(&world.work, &["show", &format!("{landing}:{file}")]),
            text.trim_end(),
            "{file}"
        );
    }
    let landed = message(&world, &landing);
    assert!(landed.contains("tracker-docs-take-main"), "{landed}");
    assert!(stated(&world, &landing).is_some(), "{landed}");

    let (composed, _) = tracker_world(&[], &[]);
    let (code, said, bases) = land_with(&composed, crates(&["a"]), |_, n| {
        if n == 0 {
            rival_moves(&composed, "b/y.txt", "b2\n");
        }
        green()
    });
    assert_eq!((code, bases.len()), (exit::PASS, 1), "{said:#?}");
    let landing = origin_main(&composed);
    let receipt = stated(&composed, &landing).expect("stated");
    assert!(receipt.composed_onto.is_some(), "{said:#?}");
    let landed = message(&composed, &landing);
    assert!(landed.contains("tracker-docs-take-main"), "{landed}");

    for (file, generated) in [("docs/PLANS.md", true), ("docs/PLAN.md", false)] {
        let world = self::world();
        let doc = |state: &str| tracker_doc("Plan", generated, state);
        seed_main(&world, &[(file, doc("ready").as_str())]);
        commit(&world.work, file, &doc("running"));
        let moved = rival_moves(&world, file, &doc("done"));
        let (code, said, bases) = land_with(&world, crates(&["a"]), |_, _| green());
        assert_eq!(
            (code, bases.len()),
            (exit::CONFLICT, 0),
            "{file}: {said:#?}"
        );
        assert_eq!(
            origin_main(&world),
            moved,
            "{file}: a conflict pushes nothing"
        );
        assert!(
            git(&world.work, &["status", "--porcelain"]).contains(&format!("UU {file}")),
            "{file}"
        );
    }
}

/// A CONFLICT WITH ONE UNCOVERED PATH RESOLVES NO PATH: main's tracker documents and its edit
/// of `shared.txt`, in one commit, conflict with the branch's tracker documents and its own edit
/// of `shared.txt`. The tracker rule would resolve `docs/PLAN.md`, but no rule covers
/// `shared.txt`, so nothing is written: both paths stay conflicted as git left them, with the
/// markers; nothing is judged or pushed.
/// CONTROL: the same world without the `shared.txt` conflict lands.
/// NEGATIVE CONTROL: a `plan` that wrote path by path would leave `docs/PLAN.md` resolved here.
#[test]
fn a_conflict_with_one_uncovered_path_resolves_no_path() {
    let mine = SHARED.replacen('4', "mine", 1);
    let theirs = SHARED.replacen('4', "theirs", 1);
    let (world, moved) = tracker_world(
        &[("shared.txt", mine.as_str())],
        &[("shared.txt", theirs.as_str())],
    );
    let (code, said, bases) = land_with(&world, crates(&["a"]), |_, _| green());
    assert_eq!(code, exit::CONFLICT, "{said:#?}");
    assert!(bases.is_empty(), "nothing is judged: {said:#?}");
    assert_eq!(origin_main(&world), moved, "a conflict pushes nothing");
    let status = git(&world.work, &["status", "--porcelain"]);
    assert!(
        status.contains("UU docs/PLAN.md") && status.contains("UU shared.txt"),
        "{status}"
    );
    let plan = std::fs::read_to_string(world.work.join("docs/PLAN.md")).expect("read");
    assert!(plan.contains("<<<<<<<"), "git's markers stay: {plan}");
    assert!(
        said.iter()
            .any(|line| line.contains("\"shared.txt\": no rule")),
        "{said:#?}"
    );

    let (lands, _) = tracker_world(&[("shared.txt", mine.as_str())], &[]);
    let (code, said, _) = land_with(&lands, crates(&["a"]), |_, _| green());
    assert_eq!(code, exit::PASS, "{said:#?}");
}

/// A CONFLICT NO RULE COVERS STOPS WITH THE CONFLICT CODE AND PUSHES NOTHING: the merge is left
/// for the person, no judgment starts, and the one line names the path and that no rule covers
/// it. The code is none of the others a landing exits with, so a landing queue tells it from a
/// red. CONTROL: a branch that merges cleanly and is judged red exits [`exit::FAILED`].
/// NEGATIVE CONTROL: a `conflicted` that returns [`exit::FAILED`] again fails the first assert.
#[test]
fn a_conflict_no_rule_covers_stops_with_the_conflict_code_and_pushes_nothing() {
    for other in [
        exit::PASS,
        exit::FAILED,
        exit::USAGE,
        exit::COULD_NOT_RUN,
        STOPPED,
    ] {
        assert_ne!(exit::CONFLICT, other, "the conflict exit is its own");
    }
    let world = world();
    commit(&world.work, "shared.txt", &SHARED.replacen('4', "mine", 1));
    let moved = rival_moves(&world, "shared.txt", &SHARED.replacen('4', "theirs", 1));
    let (code, said, bases) = land_with(&world, crates(&["a"]), |_, _| green());
    assert_eq!(code, exit::CONFLICT, "{said:#?}");
    assert!(bases.is_empty(), "a conflict starts no checks: {said:#?}");
    assert_eq!(origin_main(&world), moved, "a conflict pushes nothing");
    assert!(
        git(&world.work, &["status", "--porcelain"]).contains("UU shared.txt"),
        "the merge is left for the person"
    );
    assert!(
        said.iter().any(|line| line.contains("CONFLICT")
            && line.contains("\"shared.txt\"")
            && line.contains("no rule")),
        "{said:#?}"
    );

    let red_world = self::world();
    commit(&red_world.work, "a/x.txt", "a2\n");
    rival_moves(&red_world, "b/y.txt", "b2\n");
    let (code, said, bases) = land_with(&red_world, crates(&["a"]), |_, _| {
        ran(exit::FAILED, vec![red("test", &["-p a --lib -- mine"])], 1)
    });
    assert_eq!((code, bases.len()), (exit::FAILED, 1), "a red: {said:#?}");
}

/// ONLY THE TOOL'S OWN RESOLVED MERGES NAME RULES IN A LANDING: the branch holds a commit and a
/// merge of another branch, each whose message carries a "Resolved by rule:" paragraph. The
/// landing's message carries neither: a commit is no merge of main, and the merge's subject is
/// not this tool's. NEGATIVE CONTROL: a [`Git::resolutions`] that read every first-parent merge
/// would copy the forged merge's line.
#[test]
fn only_the_tools_own_resolved_merges_name_rules_in_a_landing() {
    let world = world();
    write(&world.work, "a/x.txt", "a2\n");
    git(&world.work, &["add", "-A"]);
    git(
        &world.work,
        &[
            "commit",
            "-q",
            "-m",
            "edit a\n\nResolved by rule:\n- forged-commit: \"a/x.txt\" (a commit)",
        ],
    );
    git(&world.work, &["checkout", "-q", "-b", "side"]);
    commit(&world.work, "a/z.txt", "z\n");
    git(&world.work, &["checkout", "-q", "feature"]);
    git(
        &world.work,
        &[
            "merge",
            "-q",
            "--no-ff",
            "--no-edit",
            "-m",
            "Merge side into feature\n\nResolved by rule:\n- forged-merge: \"a/z.txt\" (a side)",
            "side",
        ],
    );
    rival_moves(&world, "b/y.txt", "b2\n");
    let (code, said, bases) = land_with(&world, crates(&["a"]), |_, _| green());
    assert_eq!((code, bases.len()), (exit::PASS, 1), "{said:#?}");
    let landed = message(&world, &origin_main(&world));
    assert!(
        !landed.contains("Resolved by rule") && !landed.contains("forged"),
        "{landed}"
    );
}

/// A LANDING AFTER A RESTATED RESOLUTION NAMES NO RULE THAT DID NOT RUN FOR IT: a resolved
/// merge landed restated (a new commit of its tree and parents), and the checkout stayed on
/// the resolved merge, as where its move to the landing failed. A further change from there
/// lands with a message that names no rule: the one that ran did so for the landing main
/// holds. NEGATIVE CONTROL: without [`Git::restated`] the second landing copies the first's
/// rule lines.
#[test]
fn a_landing_after_a_restated_resolution_names_no_rule_that_did_not_run_for_it() {
    let (world, _) = tracker_world(&[], &[]);
    let (code, said, _) = land_with(&world, crates(&["a"]), |_, _| green());
    assert_eq!(code, exit::PASS, "{said:#?}");
    let first = origin_main(&world);
    let resolved = git(&world.work, &["rev-parse", "HEAD@{1}"]);
    let tree = |at: &str| git(&world.work, &["rev-parse", &format!("{at}^{{tree}}")]);
    assert!(
        resolved != first && tree(&resolved) == tree(&first),
        "the first landing restated the resolved merge {resolved}"
    );
    assert!(message(&world, &resolved).contains("tracker-docs-take-main"));
    git(&world.work, &["reset", "-q", "--hard", &resolved]);
    commit(&world.work, "a/x.txt", "a3\n");

    let (code, said, bases) = land_with(&world, crates(&["a"]), |_, _| green());
    assert_eq!((code, bases.len()), (exit::PASS, 1), "{said:#?}");
    let landed = message(&world, &origin_main(&world));
    assert!(!landed.contains("Resolved by rule"), "{landed}");
}

/// Where a crate's spec table sits in the worlds below.
const SPEC: &str = "crates/a/SPECS.md";

/// A `SPECS.md` stating `counts`, with its spec table's rows `specs` and its test table's rows
/// `tests` (each a header row first), and where `notes`, a third, empty table.
fn spec(counts: (usize, usize), specs: &[&str], tests: &[&str], notes: bool) -> String {
    let table = |rows: &[&str]| format!("```tsv\n{}\n```\n", rows.join("\n"));
    format!(
        "# a: specs\n\nResult: **{} specs**, sampled by **{} tests** (§2).\n\n## 1. Specs\n\n{}\n\
         ## 2. Tests\n\n{}{}",
        counts.0,
        counts.1,
        table(specs),
        table(tests),
        if notes {
            "\n## 3. Notes\n\n```tsv\n```\n"
        } else {
            ""
        }
    )
}

/// The spec table's header and the test table's.
const SPEC_HEAD: &str = "id\tkind\tstatement";
const TEST_HEAD: &str = "file\ttest\tprimary";

/// A world whose `SPECS.md` both sides changed: the branch edited `r1` (or `branch_r1`) and
/// added `r3` and its test, main edited `r2` (and `main_r1`) and added `r4` and its test, and
/// each set the counts to 3 and 3. The world and main's new tip.
fn spec_world(notes: bool, branch_r1: &str, main_r1: &str) -> (World, String) {
    let base = spec(
        (2, 2),
        &[SPEC_HEAD, "r1\tfn\tbase one", "r2\tfn\tbase two"],
        &[TEST_HEAD, "f.rs\tt1\tr1", "f.rs\tt2\tr2"],
        notes,
    );
    let ours = spec(
        (3, 3),
        &[
            SPEC_HEAD,
            branch_r1,
            "r2\tfn\tbase two",
            "r3\tfn\tbranch three",
        ],
        &[TEST_HEAD, "f.rs\tt1\tr1", "f.rs\tt2\tr2", "f.rs\tt3\tr3"],
        notes,
    );
    let theirs = spec(
        (3, 3),
        &[SPEC_HEAD, main_r1, "r2\tfn\tmain two", "r4\tfn\tmain four"],
        &[TEST_HEAD, "f.rs\tt1\tr1", "f.rs\tt2\tr2", "f.rs\tt4\tr4"],
        notes,
    );
    let world = world();
    seed_main(&world, &[(SPEC, base.as_str())]);
    commit(&world.work, SPEC, &ours);
    let moved = rival_moves(&world, SPEC, &theirs);
    (world, moved)
}

/// A SPEC TABLE CONFLICT TAKES EACH ROW'S CHANGED SIDE AND RECOUNTS: each side changed one row
/// of the spec table and added one to each table. The landed file holds the branch's edit and
/// main's, main's added rows in main's order and the branch's after them, and counts main's
/// stated numbers moved by the rows each table gained (4 and 4). The test table's first column
/// repeats, so its rows are keyed by file and test. CONTROL: with a third table the counts line
/// is plain text, which both sides set alike, so it lands as they wrote it (3 and 3).
#[test]
fn a_spec_table_conflict_takes_each_rows_changed_side_and_recounts() {
    for notes in [false, true] {
        let (world, _) = spec_world(notes, "r1\tfn\tbranch one", "r1\tfn\tbase one");
        let (code, said, bases) = land_with(&world, crates(&["a"]), |_, _| green());
        assert_eq!((code, bases.len()), (exit::PASS, 1), "{said:#?}");
        assert!(
            said.iter()
                .any(|line| line.contains("resolved by rule: spec-table-rows")),
            "{said:#?}"
        );
        let counted = if notes { (3, 3) } else { (4, 4) };
        let expected = spec(
            counted,
            &[
                SPEC_HEAD,
                "r1\tfn\tbranch one",
                "r2\tfn\tmain two",
                "r4\tfn\tmain four",
                "r3\tfn\tbranch three",
            ],
            &[
                TEST_HEAD,
                "f.rs\tt1\tr1",
                "f.rs\tt2\tr2",
                "f.rs\tt4\tr4",
                "f.rs\tt3\tr3",
            ],
            notes,
        );
        let landing = origin_main(&world);
        assert_eq!(
            git(&world.work, &["show", &format!("{landing}:{SPEC}")]),
            expected.trim_end(),
            "notes table: {notes}"
        );
    }
}

/// A SPEC ROW BOTH SIDES CHANGED DIFFERENTLY RESOLVES NOTHING: the merge is left for the
/// person, conflicted, and the line names the row. CONTROL:
/// [`a_spec_table_conflict_takes_each_rows_changed_side_and_recounts`], where one side left
/// that row alone.
#[test]
fn a_spec_row_both_sides_changed_differently_resolves_nothing() {
    let (world, moved) = spec_world(false, "r1\tfn\tbranch one", "r1\tfn\tmain one");
    let (code, said, bases) = land_with(&world, crates(&["a"]), |_, _| green());
    assert_eq!((code, bases.len()), (exit::CONFLICT, 0), "{said:#?}");
    assert_eq!(origin_main(&world), moved, "a conflict pushes nothing");
    assert!(
        git(&world.work, &["status", "--porcelain"]).contains(&format!("UU {SPEC}")),
        "{said:#?}"
    );
    assert!(
        said.iter()
            .any(|line| line.contains("row `r1` changed differently on both sides")),
        "{said:#?}"
    );
}

/// A SPEC TABLE'S KEY OF ONE OR TWO COLUMNS MUST BE UNIQUE, and the rule refuses what it
/// cannot carry over whole. A table keyed by file and test (its first column repeats) merges
/// both sides' rows; one whose rows repeat their first two cells, prose both sides edited, and
/// a branch that only reordered rows are each refused.
#[test]
fn a_spec_key_of_one_or_two_columns_must_be_unique() {
    let table = |prose: &str, rows: &[&str]| {
        format!("# T\n\n{prose}\n\n```tsv\n{}\n```\n", rows.join("\n"))
    };
    let base = table("prose", &["file\ttest", "f\tt1", "f\tt2"]);
    let ours = table("prose", &["file\ttest", "f\tt1", "f\tt2", "f\tt3"]);
    let theirs = table("prose", &["file\ttest", "f\tt1", "f\tt2", "f\tt4"]);
    let (merged, _) = resolve::spec_table(&base, &ours, &theirs).expect("keyed by file and test");
    assert_eq!(
        merged,
        table("prose", &["file\ttest", "f\tt1", "f\tt2", "f\tt4", "f\tt3"])
    );

    let repeated = |last: &str| table("prose", &["file\ttest\tx", "f\tt1\ta", "f\tt1\tb", last]);
    let refused = resolve::spec_table(
        &repeated("f\tt2\tc"),
        &repeated("f\tt2\tours"),
        &repeated("f\tt2\ttheirs"),
    )
    .unwrap_err();
    assert!(
        refused.contains("no key of one or two columns is unique"),
        "{refused}"
    );

    let refused = resolve::spec_table(
        &base,
        &table("branch prose", &["file\ttest", "f\tt1", "f\tt2", "f\tt3"]),
        &table("main prose", &["file\ttest", "f\tt1", "f\tt2", "f\tt4"]),
    )
    .unwrap_err();
    assert!(refused.contains("outside the tables"), "{refused}");

    let refused = resolve::spec_table(
        &base,
        &table("prose", &["file\ttest", "f\tt2", "f\tt1"]),
        &theirs,
    )
    .unwrap_err();
    assert!(refused.contains("reordered"), "{refused}");
}

/// THE LAND'S RULE SOURCES READ NO MEMBER'S SPEC TABLE AND NO TRACKER DOCUMENT: the search
/// `verify land` counts readers by ([`super::super::reads`], which [`super::super::Git`]'s
/// `readers` applies to each file) passes over this crate's landing and cone rule sources and
/// their tests, so a landing whose branch and moved main both changed a member's `SPECS.md`,
/// `docs/PLAN.md` or `docs/STATUS.md` is not judged again for them. Read here as the live tree
/// holds them: the rule's source, the land's and the cone's, and this file with its fixture
/// paths. NEGATIVE CONTROL: each of those texts in a file of this crate that is no rule source
/// is a reader of every member's table, and the rule's source there of the tracker documents
/// too; census's search alone ([`aterm_census::no_reach::may_read`]) counts the land's source,
/// whose strings spell a bare table name, wherever this crate holds it.
#[test]
fn the_lands_rule_sources_read_no_members_spec_table() {
    let reads = super::super::reads;
    let sources = [
        ("land_resolve.rs", include_str!("land_resolve.rs")),
        ("land.rs", include_str!("land.rs")),
        ("changed.rs", include_str!("changed.rs")),
        (
            "land_resolve_tests.rs",
            include_str!("land_resolve_tests.rs"),
        ),
    ];
    let tables = ["crates/aterm-gui/SPECS.md", "crates/atpkg/SPECS.md"];
    let elsewhere = "crates/aterm-verify/src/perf/rule.rs";
    for (name, source) in sources {
        let file = format!("crates/aterm-verify/src/{name}");
        for path in tables.into_iter().chain(["docs/PLAN.md", "docs/STATUS.md"]) {
            assert!(!reads(&file, source, path), "{file} reads {path}");
        }
        for table in tables {
            assert!(reads(elsewhere, source, table), "{name} elsewhere: {table}");
        }
    }
    for tracker in ["docs/PLAN.md", "docs/STATUS.md"] {
        assert!(reads(elsewhere, sources[0].1, tracker), "{tracker}");
    }
    assert!(aterm_census::no_reach::may_read(
        "crates/aterm-verify/src/land.rs",
        sources[1].1,
        tables[0]
    ));
}

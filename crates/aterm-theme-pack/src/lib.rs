//! aterm's community theme pack: well-known third-party palettes whose own
//! projects carry a permissive licence, embedded with their notices and
//! installed on request as ordinary files in the themes folder.
//!
//! The data lives in `contrib/themes/pack/` (its README says how to add a
//! theme): each palette's file from the iTerm2-Color-Schemes collection,
//! vendored byte for byte under `upstream/` at one pinned commit, each
//! project's licence under `LICENSES/`, one manifest row per theme, and the
//! shipped `<id>.conf` files, which are generated by [`derive`] (the native
//! converter, `aterm_types::scheme_import`, plus a header naming the
//! palette's author, project, licence and the collection) and never edited.
//! The build script embeds the `.conf` files and the licence texts; this
//! crate reads no file of its own at run time and fetches nothing.
//!
//! A pack theme is never an implicit built-in: the catalog only sees one
//! once [`install`] has copied its file into the themes folder, through the
//! one atomic writer every theme file goes through
//! (`aterm_types::scheme_install::write_atomically`). `aterm theme pack`,
//! `aterm theme install` and Settings ▸ Themes ▸ Get More are the front doors.

mod policy;

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use aterm_types::Appearance;
use aterm_types::scheme::{self, ParsedTheme};
use aterm_types::scheme_import::{self, ImportFormat};
use aterm_types::scheme_install::{self, InstallError};

pub use policy::{ADMITTED_LICENCES, admitted};

/// One theme of the pack.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct PackTheme {
    /// The theme's id: its file stem in the themes folder, what
    /// `theme = "<id>"` names. The collection's own name for it.
    pub id: &'static str,
    /// The theme file the pack installs, byte for byte.
    pub text: &'static str,
    /// The file it was converted from: `upstream/<upstream>` in the pack,
    /// `ghostty/<upstream>` in the collection.
    pub upstream: &'static str,
    /// The appearance it is drawn for (declared in the file).
    pub appearance: Appearance,
    /// Its family's theme for the other appearance: a pack id or a
    /// built-in's name.
    pub pair: Option<&'static str>,
    /// Who the palette is by.
    pub author: &'static str,
    /// The palette's project, `owner/repo` on GitHub.
    pub project: &'static str,
    /// The project's home page.
    pub project_url: &'static str,
    /// The project's licence, an SPDX id in [`ADMITTED_LICENCES`].
    pub licence: &'static str,
    /// The licence files (paths under the pack folder, `LICENSES/…`) whose
    /// notices the theme's file carries: the project's, and a port's when
    /// the collection took the palette from one.
    pub licence_files: &'static [&'static str],
}

/// Where the pack's upstream files come from.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Collection {
    /// `owner/repo` on GitHub.
    pub repo: &'static str,
    /// The commit `upstream/` was taken at.
    pub commit: &'static str,
    /// The collection's own licence file under the pack folder.
    pub licence_file: &'static str,
}

include!(concat!(env!("OUT_DIR"), "/pack.rs"));

/// Every pack theme, sorted by id ignoring ASCII case.
#[must_use]
pub fn themes() -> &'static [PackTheme] {
    THEMES
}

/// The pack theme `id` names, ignoring ASCII case (as the catalog does).
#[must_use]
pub fn find(id: &str) -> Option<&'static PackTheme> {
    THEMES
        .iter()
        .find(|theme| theme.id.eq_ignore_ascii_case(id))
}

/// The text of the licence file `file` (`LICENSES/…`), if the pack has it.
#[must_use]
pub fn licence_text(file: &str) -> Option<&'static str> {
    LICENCES
        .iter()
        .find(|(name, _)| *name == file)
        .map(|(_, text)| *text)
}

/// Every licence file the pack embeds, `(path, text)`, sorted by path.
#[must_use]
pub fn licences() -> &'static [(&'static str, &'static str)] {
    LICENCES
}

/// Where the pack's upstream files come from.
#[must_use]
pub fn collection() -> &'static Collection {
    &COLLECTION
}

/// The licence file for a built-in port's source `project`: by the build's
/// rule, `LICENSES/<spdx>-<repo>.txt`, checked to exist and embedded at build
/// time for every built-in's source.
#[must_use]
pub fn port_licence_file(project: &str) -> Option<&'static str> {
    PORTS
        .iter()
        .find(|(name, _)| *name == project)
        .map(|(_, file)| *file)
}

/// The Apache-2.0 short notice a copy carries in place of the whole licence.
const APACHE_NOTICE: [&str; 6] = [
    "Licensed under the Apache License, Version 2.0 (the \"License\"); you may not",
    "use this file except in compliance with the License. You may obtain a copy of",
    "the License at http://www.apache.org/licenses/LICENSE-2.0 ; aterm prints it",
    "with `aterm theme pack --licences`. Unless required by applicable law or agreed",
    "to in writing, it is distributed on an \"AS IS\" BASIS, WITHOUT WARRANTIES OR",
    "CONDITIONS OF ANY KIND, either express or implied.",
];

/// The copyright lines of a licence text, without the appendix's
/// `Copyright [yyyy] [name of copyright owner]` template.
fn copyright_lines(licence: &str) -> impl Iterator<Item = &str> {
    licence.lines().map(str::trim).filter(|line| {
        line.starts_with("Copyright") && !line.contains("[yyyy]") && !line.contains("[name of")
    })
}

/// The notice a file under `spdx` carries for `licence` (the licence file's
/// text): the whole text for a notice-carrying licence, else (Apache-2.0)
/// the copyright lines and the short notice.
fn notice_lines(spdx: &str, licence: &str) -> Vec<String> {
    if policy::notice_is_whole_text(spdx) {
        return licence.lines().map(str::to_string).collect();
    }
    copyright_lines(licence)
        .map(str::to_string)
        .chain(APACHE_NOTICE.iter().map(|line| (*line).to_string()))
        .collect()
}

/// The pack's file for `theme`, generated from `upstream_text` (the
/// collection's ghostty file), `licences` (the texts of
/// `theme.licence_files`, in order) and the collection's licence: the native
/// converter's output with the theme's identity stamped on it and a header of
/// provenance and notices. The one generator: the bless step writes its
/// output, and the integrity test holds the embedded file to it.
///
/// # Errors
/// The upstream file does not convert, or the result does not read back as
/// what was converted.
pub fn derive(
    theme: &PackTheme,
    upstream_text: &str,
    licences: &[&str],
    collection_licence: &str,
) -> Result<String, String> {
    let mut report = scheme_import::convert(ImportFormat::Ghostty, upstream_text, None)
        .map_err(|error| format!("{}: {error}", theme.upstream))?;
    report.scheme.name = theme.id.to_string();
    report.author = Some(theme.author.to_string());
    report.description = Some(format!(
        "{} from {} ({}), via iTerm2-Color-Schemes",
        theme.upstream, theme.project, theme.licence
    ));
    report.scheme.appearance = theme.appearance;
    report.appearance_declared = true;

    let commit = COLLECTION.commit.get(..12).unwrap_or(COLLECTION.commit);
    let dropped = if report.dropped.is_empty() {
        "nothing".to_string()
    } else {
        report.dropped.join(", ")
    };
    let spdx = if theme.licence == "MIT" {
        "MIT".to_string()
    } else {
        format!("{} AND MIT", theme.licence)
    };
    let mut header = vec![
        format!(
            "{}: aterm community theme pack (contrib/themes/pack).",
            theme.id
        ),
        format!(
            "Palette: {} by {}, {}",
            theme.upstream, theme.author, theme.project_url
        ),
        format!(
            "Converted by aterm from iTerm2-Color-Schemes ghostty/{} at {commit}",
            theme.upstream
        ),
        format!(
            "  (https://github.com/{}); dropped: {dropped}.",
            COLLECTION.repo
        ),
        String::new(),
        format!("SPDX-License-Identifier: {spdx}"),
    ];
    for licence in licences {
        header.push(String::new());
        let lines = notice_lines(theme.licence, licence);
        if !policy::notice_is_whole_text(theme.licence) && copyright_lines(licence).next().is_none()
        {
            header.push(format!("Copyright {}", theme.author));
        }
        header.extend(lines);
    }
    header.push(String::new());
    header.push("The iTerm2-Color-Schemes collection:".to_string());
    header.extend(collection_licence.lines().map(str::to_string));
    let header: Vec<&str> = header.iter().map(String::as_str).collect();
    let text = report.to_native_conf(&header);

    let expected = ParsedTheme::colours_only(
        report.scheme.clone(),
        true,
        report.description.clone(),
        report.author.clone(),
    );
    match scheme::parse_theme_str(&text) {
        Ok(read_back) if read_back == expected => Ok(text),
        Ok(_) => Err(format!(
            "{}: the file does not read back unchanged",
            theme.id
        )),
        Err(error) => Err(format!(
            "{}: the file does not read back ({error})",
            theme.id
        )),
    }
}

/// Whether `text` carries the notice a file under `spdx` owes `licence`
/// (a licence file's text): every non-blank line of it, in order, as a
/// `# <line>` comment line.
#[must_use]
pub fn carries_notice(text: &str, spdx: &str, licence: &str) -> bool {
    let mut comments = text.lines().filter_map(|line| line.strip_prefix("# "));
    notice_lines(spdx, licence)
        .iter()
        .map(|line| line.trim_end())
        .filter(|line| !line.trim().is_empty())
        .all(|wanted| comments.any(|line| line == wanted))
}

/// Where a pack theme stands in a themes folder.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum PackState {
    /// No `<id>.conf`.
    Absent,
    /// `<id>.conf` is the pack's file, byte for byte.
    Installed,
    /// `<id>.conf` is there but differs (edited, or another theme by that
    /// name), or is not a regular file.
    Modified,
    /// A file whose name differs from `<id>.conf` only in case: the catalog
    /// would load neither, so the pack will not add the second.
    CaseVariant(PathBuf),
}

/// Where `theme` stands in the themes folder `dir`.
#[must_use]
pub fn state_in(dir: &Path, theme: &PackTheme) -> PackState {
    if let Some(other) = scheme_install::case_variant(dir, theme.id) {
        return PackState::CaseVariant(other);
    }
    let path = dir.join(format!("{}.conf", theme.id));
    match std::fs::symlink_metadata(&path) {
        Err(_) => PackState::Absent,
        Ok(meta) if !meta.is_file() => PackState::Modified,
        Ok(_) => match scheme_install::read_bounded(&path) {
            Ok(bytes) if bytes == theme.text.as_bytes() => PackState::Installed,
            _ => PackState::Modified,
        },
    }
}

/// What [`install`] did.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum PackInstall {
    /// Wrote the pack's file here.
    Wrote(PathBuf),
    /// The pack's file was already here, unchanged.
    Unchanged(PathBuf),
}

/// Copy `theme`'s file into the themes folder `dir` (`None`: none could be
/// found) as `<id>.conf`. An existing different file is kept unless
/// `replace`.
///
/// # Errors
/// [`InstallError::Failed`] with no folder, a same-name file in another
/// case, a pack copy that does not parse, or a failed write;
/// [`InstallError::Refused`] for a built-in's name;
/// [`InstallError::Exists`] when a different `<id>.conf` is there and
/// `replace` is false.
pub fn install(
    theme: &PackTheme,
    dir: Option<&Path>,
    replace: bool,
) -> Result<PackInstall, InstallError> {
    if let Err(why) = scheme::validate_user_theme_name(theme.id) {
        return Err(InstallError::Refused(format!(
            "{:?} cannot be a theme id: {why}",
            theme.id
        )));
    }
    let Some(dir) = dir else {
        return Err(InstallError::Failed(
            "no themes folder: neither XDG_CONFIG_HOME, APPDATA nor HOME is set".to_string(),
        ));
    };
    if let Some(builtin) = scheme::builtin_names()
        .into_iter()
        .find(|builtin| builtin.eq_ignore_ascii_case(theme.id))
    {
        return Err(InstallError::Refused(format!(
            "{:?} is the built-in theme {builtin:?}",
            theme.id
        )));
    }
    let dest = dir.join(format!("{}.conf", theme.id));
    match state_in(dir, theme) {
        PackState::CaseVariant(other) => {
            return Err(InstallError::Failed(
                scheme_install::case_collision_message(&other, theme.id),
            ));
        }
        PackState::Installed => return Ok(PackInstall::Unchanged(dest)),
        PackState::Absent | PackState::Modified => {}
    }
    if scheme::parse_theme_str(theme.text).is_err() {
        return Err(InstallError::Failed(format!(
            "the pack copy of {} does not parse",
            theme.id
        )));
    }
    scheme_install::write_atomically(dir, &dest, theme.id, theme.text.as_bytes(), replace)?;
    Ok(PackInstall::Wrote(dest))
}

/// The attribution text for every third-party palette aterm carries: the
/// collection, each pack project with its themes, each built-in port's
/// source, then the text of every licence file. `ATTRIBUTION.md` in the pack
/// folder is this, and `aterm theme pack --licences` prints it.
#[must_use]
pub fn notices() -> String {
    let mut out = String::new();
    out.push_str(
        "# Colour theme attribution\n\n\
         aterm's built-in theme ports and its community theme pack\n\
         (contrib/themes/pack/) use colour palettes from the projects below, each\n\
         under its own licence. Every pack theme file carries its notices too.\n\
         This file is generated (aterm_theme_pack::notices); do not edit it.\n\n\
         ## The community theme pack\n\n",
    );
    let _ = writeln!(
        out,
        "The pack's files are converted from the ghostty/ folder of\n\
         https://github.com/{} at commit\n{}, under the MIT licence ({}).\n\
         Each palette belongs to its author:\n",
        COLLECTION.repo, COLLECTION.commit, COLLECTION.licence_file
    );
    let mut projects: Vec<&str> = THEMES.iter().map(|theme| theme.project).collect();
    projects.sort_by_key(|project| project.to_ascii_lowercase());
    projects.dedup();
    for project in projects {
        let members: Vec<&PackTheme> = THEMES.iter().filter(|t| t.project == project).collect();
        let Some(first) = members.first() else {
            continue;
        };
        let ids: Vec<&str> = members.iter().map(|t| t.id).collect();
        let _ = writeln!(
            out,
            "- {project} by {} ({}; {}): {}\n  {}",
            first.author,
            first.licence,
            first.licence_files.join(", "),
            ids.join(", "),
            first.project_url
        );
    }
    out.push_str("\n## Built-in theme ports\n\n");
    let mut sources: Vec<(scheme::BuiltinSource, Vec<&str>)> = Vec::new();
    for builtin in scheme::builtin_theme_list() {
        let Some(source) = builtin.source else {
            continue;
        };
        match sources
            .iter_mut()
            .find(|(s, _)| s.project == source.project)
        {
            Some((_, names)) => names.push(builtin.name),
            None => sources.push((source, vec![builtin.name])),
        }
    }
    for (source, names) in &sources {
        let _ = writeln!(
            out,
            "- {} ({}; {}): {}\n  {}",
            source.project,
            source.licence,
            port_licence_file(source.project).unwrap_or("no licence file"),
            names.join(", "),
            source.url
        );
    }
    out.push_str("\n## Licence texts\n");
    for (file, text) in LICENCES {
        let _ = write!(out, "\n### {file}\n\n");
        for line in text.lines() {
            if line.trim().is_empty() {
                out.push('\n');
            } else {
                let _ = writeln!(out, "    {}", line.trim_end());
            }
        }
    }
    out
}


//! Build script that decodes `data/lexicon.toml`, `data/exceptions.toml` and `data/tricks.toml`
//! into `$OUT_DIR`.

#[path = "src/raw.rs"]
#[expect(
    dead_code,
    reason = "the build reads every row field but the override marker, `user`"
)]
mod raw;

use std::fmt::Write as _;
use std::path::Path;

fn main() {
    let dir = std::path::PathBuf::from(
        std::env::var_os("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR"),
    );
    let out = std::path::PathBuf::from(
        std::env::var_os("OUT_DIR").expect("cargo sets OUT_DIR for a build script"),
    );
    let lexicon_path = dir.join("data/lexicon.toml");
    let exceptions_path = dir.join("data/exceptions.toml");
    let tricks_path = dir.join("data/tricks.toml");
    println!("cargo:rerun-if-changed={}", lexicon_path.display());
    println!("cargo:rerun-if-changed={}", exceptions_path.display());
    println!("cargo:rerun-if-changed={}", tricks_path.display());
    println!("cargo:rerun-if-changed=src/raw.rs");

    let lexicon: raw::RawLexicon = decode(&lexicon_path);
    let exceptions: raw::RawExceptions = decode(&exceptions_path);

    let mut code = String::from(
        "// Generated by build.rs from data/lexicon.toml and data/exceptions.toml.\n\
         static BUILTIN_ENTRIES: &[BuiltinEntry] = &[\n",
    );
    for e in &lexicon.entry {
        let _ = writeln!(
            code,
            "    BuiltinEntry {{ class: {:?}, lang: {:?}, mode: {:?}, stems: &{}, suffixes: &{}, \
             forms: &{}, cjk: {}, ambiguous: {}, species: {:?} }},",
            e.class,
            e.lang,
            e.mode,
            list(&e.stems),
            list(&e.suffixes),
            list(&e.forms),
            e.cjk,
            e.ambiguous,
            e.species,
        );
    }
    code.push_str("];\nstatic BUILTIN_EXCEPTION_WORDS: &[&str] = &[\n");
    for x in &exceptions.exception {
        let _ = writeln!(code, "    {:?},", x.word);
    }
    code.push_str("];\n");
    write(&out.join("builtin_lexicon.rs"), &code);
    write(
        &out.join("builtin_tricks.rs"),
        &tricks_code(&decode(&tricks_path)),
    );
}

/// `data/tricks.toml`'s rows, in file order, as the statics `src/tricks.rs` rebuilds them from.
fn tricks_code(tricks: &raw::RawTricks) -> String {
    let mut code = String::from(
        "// Generated by build.rs from data/tricks.toml.\n\
         static BUILTIN_TRICK_ROWS: &[BuiltinTrickRow] = &[\n",
    );
    for r in &tricks.trick {
        let _ = writeln!(
            code,
            "    BuiltinTrickRow {{ id: {:?}, lang: {:?}, words: &{}, address: &{}, gated: {}, \
             cjk: {}, unglued: &{} }},",
            r.id,
            r.lang,
            list(&r.words),
            list(&r.address),
            r.gated,
            r.cjk,
            list(&r.unglued),
        );
    }
    for (name, rows) in [
        ("BUILTIN_VOCATIVE_ROWS", &tricks.vocative),
        ("BUILTIN_FILLER_ROWS", &tricks.filler),
    ] {
        let _ = writeln!(code, "];\nstatic {name}: &[BuiltinWordRow] = &[");
        for r in rows {
            let _ = writeln!(
                code,
                "    BuiltinWordRow {{ lang: {:?}, words: &{}, gated: {}, cjk: {}, unglued: &{} }},",
                r.lang,
                list(&r.words),
                r.gated,
                r.cjk,
                list(&r.unglued),
            );
        }
    }
    code.push_str("];\n");
    code
}

/// Write `code` to `target`, or the build stops naming the file.
fn write(target: &Path, code: &str) {
    if let Err(e) = std::fs::write(target, code) {
        panic!("could not write {}: {e}", target.display());
    }
}

/// `path` decoded as `T`, or the build stops naming the file and the error.
fn decode<T: serde::de::DeserializeOwned>(path: &Path) -> T {
    let text = std::fs::read_to_string(path)
        .unwrap_or_else(|e| panic!("could not read {}: {e}", path.display()));
    aterm_toml::from_str(&text)
        .unwrap_or_else(|e| panic!("{} does not decode: {e}", path.display()))
}

/// `items` as a Rust array literal of string literals.
fn list(items: &[String]) -> String {
    let mut out = String::from("[");
    for (i, item) in items.iter().enumerate() {
        if i > 0 {
            out.push_str(", ");
        }
        let _ = write!(out, "{item:?}");
    }
    out.push(']');
    out
}

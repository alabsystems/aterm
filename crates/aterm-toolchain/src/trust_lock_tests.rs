const ROOT: &str = "46ca692db799c27b4874df3de5c635ddb0845d32ff2d23cb2546e613dc5626f1";
const COMMIT: &str = "29ebb403de7a102850d6cb10a62d5cc3baf723ed";

fn sample() -> TrustLock {
    TrustLock {
        build: 16387,
        tree_root: ROOT.to_string(),
        compiler_commit: COMMIT.to_string(),
        receipt:
            "SEED-MINT sha256:4cd1415f6a19170ee60a26f5fdb2e799e3fc2dbfc939caff1c64a83fa554c620"
                .to_string(),
        stock_toolchain: "1.99.1".to_string(),
    }
}

fn scratch(tag: &str) -> PathBuf {
    aterm_tempfile::Builder::new()
        .prefix(&format!("{tag}."))
        .tempdir()
        .expect("tempdir")
        .keep()
}

#[test]
fn a_rendered_lock_reads_back_with_its_head() {
    let text = format!(
        "# @generated by adopt (seal 0000000000000000); rerun it, never edit by hand.\n{}",
        render_body(&sample())
    );
    assert_eq!(parse(&text), Ok(sample()));
}


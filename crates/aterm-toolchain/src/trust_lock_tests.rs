fn a_receipt_with_quotes_and_backslashes_round_trips() {
    let mut lock = sample();
    lock.receipt = "a \"quoted\" \\ receipt\twith a tab".to_string();
    assert_eq!(parse(&render_body(&lock)), Ok(lock));
}

#[test]
fn anything_but_the_generated_shape_is_refused() {
    let body = render_body(&sample());
    let cases: Vec<(String, &str)> = vec![
        (body.replace("version = 1", "version = 2"), "version 2"),
        (body.replace("version = 1\n", ""), "no `version`"),
        (
            body.replace("[stock]", "[other]"),
            "unknown table `[other]`",
        ),
        (body.replace("build = 16387\n", ""), "no `trust.build`"),
        (
            body.replace("build = 16387", "build = 16387\nbuild = 16388"),
            "`build` given twice",
        ),
        (
            body.replace("build = 16387", "build = \"16387\""),
            "not a whole number",
        ),
        (
            body.replace(ROOT, &ROOT.to_uppercase()),
            "not 64 lowercase hex",
        ),
        (body.replace(COMMIT, &COMMIT[..12]), "not 40 lowercase hex"),
        (
            body.replace("receipt = \"SEED", "receipt = SEED"),
            "not one quoted string",
        ),
        (body.replace("1.99.1", "stable"), "not an exact release"),
        (
            body.replace("[stock]", "channel = \"trust\"\n[stock]"),
            "unknown key `trust.channel`",
        ),
        (format!("extra = 1\n{body}"), "unknown key `extra`"),
    ];
    for (text, says) in cases {
        let refused = parse(&text).expect_err(&text);
        assert!(refused.contains(says), "{says:?} not in {refused:?}");
    }
}

#[test]
fn the_nearest_lock_on_the_walk_up_wins_and_none_is_none() {
    let root = scratch("trust-lock-find");
    let nested = root.join("a/b/c");
    std::fs::create_dir_all(&nested).expect("mkdir");
    assert_eq!(find(&nested), None);
    std::fs::write(root.join(LOCK_FILE), render_body(&sample())).expect("write");
    let found = find(&nested).expect("the root's lock");
    assert_eq!(found.path, root.join(LOCK_FILE));
    assert_eq!(found.root(), root.as_path());
    assert_eq!(found.lock, Ok(sample()));
    let mut inner = sample();
    inner.build = 9;
    std::fs::write(root.join("a").join(LOCK_FILE), render_body(&inner)).expect("write");
    assert_eq!(find(&nested).expect("the inner lock").lock, Ok(inner));
}

#[test]
fn a_lock_that_cannot_be_read_is_found_and_refused_never_skipped() {
    let root = scratch("trust-lock-unreadable");
    let nested = root.join("a");
    std::fs::create_dir_all(nested.join(LOCK_FILE)).expect("a directory at the name");
    std::fs::write(root.join(LOCK_FILE), render_body(&sample())).expect("write");
    let found = find(&nested).expect("the unreadable lock is the nearest");
    assert_eq!(found.path, nested.join(LOCK_FILE));
    assert!(found.lock.is_err(), "{found:?}");
    std::fs::remove_dir(nested.join(LOCK_FILE)).expect("rmdir");
    std::fs::write(
        nested.join(LOCK_FILE),
        vec![b'#'; MAX_ATERM_CONFIG_BYTES + 1],
    )
    .expect("write");
    assert!(find(&nested).expect("oversize").lock.is_err());
}

fn store_build(prefix: &Path, build: u64, root: Option<&str>) {
    let bin = build_dir(prefix, build).join("bin");
    std::fs::create_dir_all(&bin).expect("mkdir");
    std::fs::write(ready_marker(prefix, build), "ok\n").expect("ready");
    let targo = bin.join(tool_file("targo"));
    crate::test_script::script(&targo, "#!/bin/sh\nexit 0\n");
    if let Some(root) = root {
        write_tree_root_record(&build_dir(prefix, build), root).expect("record");
    }
}

#[test]
fn the_store_answers_the_locked_build_only_with_the_locks_tree() {
    let prefix = scratch("trust-lock-store");
    let lock = sample();
    assert_eq!(locked_build(&prefix, &lock), LockedBuild::Absent);
    store_build(&prefix, lock.build, None);
    assert_eq!(locked_build(&prefix, &lock), LockedBuild::Unrecorded);
    let other = "1".repeat(64);
    store_build(&prefix, lock.build, Some(&other));
    assert_eq!(
        locked_build(&prefix, &lock),
        LockedBuild::Mismatch { recorded: other }
    );
    store_build(&prefix, lock.build, Some(ROOT));
    assert_eq!(
        locked_build(&prefix, &lock),
        LockedBuild::Present {
            bin: build_dir(&prefix, lock.build).join("bin")
        }
    );
    assert_eq!(
        tree_root_record(&prefix, 16387),
        prefix.join("store/trust/16387.tree_root")
    );
    // A tree whose install never completed (or whose resolve check refused it while a hold
    // kept it) is no build, whatever its record says.
    std::fs::remove_file(ready_marker(&prefix, lock.build)).expect("unmark");
    assert_eq!(locked_build(&prefix, &lock), LockedBuild::Absent);
}

/// A REFUSAL NAMES WHAT PUTS THE LOCK'S BUILD HERE: the build's install where one is published
/// for this machine, and, where the store's signed manifests say none is (`Found::unpublished`),
/// why, and the local sysroot the caller's own resolution takes in the lock's place, never an
/// install that cannot succeed; a store reader's names no `TRUST_STAGE2_BIN`, which it never
/// reads; neither says "Mac". NEGATIVE CONTROL (2026-11-11): with `refusal`'s `fix` ignoring
/// `found.unpublished`, the unpublished `Absent` refusal still read "run `aterm pkg install trust
/// --build 16387`".
#[test]
fn a_refusal_names_what_puts_the_locks_build_here() {
    let lock = sample();
    let published = Found {
        path: PathBuf::from("/c/trust.lock"),
        lock: Ok(lock.clone()),
        unpublished: None,
    };
    let why = "unavailable on aarch64-unknown-linux-gnu: Trust is published for ARM macOS only";
    let unpublished = Found {
        unpublished: Some(why.to_string()),
        ..published.clone()
    };
    let states = [
        LockedBuild::Absent,
        LockedBuild::Unrecorded,
        LockedBuild::Mismatch {
            recorded: "1".repeat(64),
        },
    ];
    for state in &states {
        let install = state
            .refusal(&published, &lock, LOCAL_SYSROOT_REMEDY)
            .expect("refused");
        assert!(
            install.contains("run `aterm pkg install trust --build 16387`"),
            "{install}"
        );
        let local = state
            .refusal(&unpublished, &lock, LOCAL_SYSROOT_REMEDY)
            .expect("refused");
        assert!(
            local.contains(&format!(
                "no published install of it serves this machine ({why}); \
                 {LOCAL_SYSROOT_REMEDY}"
            )),
            "{local}"
        );
        assert!(!local.contains("pkg install"), "{local}");
        assert!(!local.contains("TRUST_STAGE2_BIN"), "{local}");
        for line in [&install, &local] {
            assert!(
                line.contains("this machine's store") && !line.contains("Mac"),
                "{line}"
            );
        }
    }
    assert_eq!(
        LockedBuild::Present {
            bin: PathBuf::from("/b")
        }
        .refusal(&unpublished, &lock, LOCAL_SYSROOT_REMEDY),
        None
    );
}

/// A record binds the tree it was taken of: a tree re-staged under the same number (a new
/// directory swapped into place), or a record bound to another identity, reads as unrecorded
/// until it is recorded again, while a rename of the same tree aside (`<build>.noindex`
/// behind a link) keeps it, read through either name.
#[cfg(unix)]
#[test]
fn a_record_names_the_tree_it_was_taken_of() {
    let prefix = scratch("trust-lock-identity");
    let lock = sample();
    store_build(&prefix, lock.build, Some(ROOT));
    let dir = build_dir(&prefix, lock.build);
    let aside = dir.with_file_name(format!("{}.noindex", lock.build));
    std::fs::rename(&dir, &aside).expect("lay aside");
    std::os::unix::fs::symlink(format!("{}.noindex", lock.build), &dir).expect("link");
    assert!(matches!(
        locked_build(&prefix, &lock),
        LockedBuild::Present { .. }
    ));
    assert_eq!(
        recorded_root_at(&aside).as_deref(),
        Some(ROOT),
        "the aside tree, as a canonical path names it, reads the build's record"
    );
    // A fold's record bound to the identity it began on describes no tree swapped in since.
    write_tree_root_record_as(&dir, "1:2", ROOT).expect("record");
    assert_eq!(locked_build(&prefix, &lock), LockedBuild::Unrecorded);
    write_tree_root_record_as(&dir, &identity_or_dash(&dir), ROOT).expect("record");
    let restaged = prefix.join("restaged");
    std::fs::create_dir_all(&restaged).expect("mkdir");
    std::fs::rename(aside.join("bin"), restaged.join("bin")).expect("move bin");
    std::fs::remove_dir(&aside).expect("rmdir");
    std::fs::rename(&restaged, &aside).expect("swap in");
    assert_eq!(locked_build(&prefix, &lock), LockedBuild::Unrecorded);
    // Negative control: the record itself is still there and still names the lock's root.
    let text = std::fs::read_to_string(tree_root_record(&prefix, lock.build)).expect("read");
    assert!(text.contains(ROOT), "{text}");
}

#[test]
fn a_resolution_marks_the_build_and_the_mark_keeps_it_for_the_window() {
    let prefix = scratch("trust-lock-mark");
    store_build(&prefix, 7, None);
    let dir = build_dir(&prefix, 7);
    let now = std::time::SystemTime::now();
    assert!(!locked_within_keep(&dir, now), "no mark, nothing kept");
    mark_locked(&prefix, 7).expect("mark");
    assert!(locked_within_keep(&dir, now));
    let later = now + LOCKED_KEEP + std::time::Duration::from_secs(60);
    assert!(
        !locked_within_keep(&dir, later),
        "a mark past the window keeps nothing"
    );
    let old = now - LOCKED_KEEP - std::time::Duration::from_secs(60);
    std::fs::OpenOptions::new()
        .write(true)
        .open(locked_mark(&prefix, 7))
        .expect("open")
        .set_modified(old)
        .expect("age it");
    assert!(!locked_within_keep(&dir, now));
    mark_locked(&prefix, 7).expect("a stale mark is renewed");
    assert!(locked_within_keep(&dir, now));
}

#[cfg(unix)]
#[test]
fn the_compiler_commit_is_what_trustc_answers() {
    let bin = scratch("trust-lock-commit").join("bin");
    std::fs::create_dir_all(&bin).expect("mkdir");
    let trustc = bin.join("trustc");
    crate::test_script::script(
        &trustc,
        &format!("#!/bin/sh\necho 'rustc 1.101.0-dev'\necho 'commit-hash: {COMMIT}'\n"),
    );
    assert_eq!(compiler_commit(&bin).as_deref(), Some(COMMIT));
    crate::test_script::script(&trustc, "#!/bin/sh\necho 'commit-hash: unknown'\n");
    assert_eq!(compiler_commit(&bin), None);
}

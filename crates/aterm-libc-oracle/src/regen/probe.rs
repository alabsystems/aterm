//! The const-eval probes: ABI facts measured by the compiler for each triple.
//!
//! Each fact is a `const _: [(); 999999] = [(); <expr>];` line. The lengths
//! mismatch, so the compiler REPORTS `<expr>`'s value in its E0308 diagnostic
//! ("found one with a size of N") — measured even for a triple this box cannot
//! execute. The probe never links and never runs. Three passes:
//!
//! 1. size and alignment of every named type, offset of every public field;
//! 2. the bytes of each struct-valued constant (sized by pass 1);
//! 3. size and alignment of every field type (the layout engine's input).

use std::collections::BTreeMap;
use std::fmt;

use super::decls::Decls;
use super::layout::TypeSizes;
use super::shim::const_expr;
use crate::cargo::{Diagnostic, Outcome, tail};
use crate::cells::Cell;

/// The reference crate the probe measures, at the version the shim replaces.
pub const MANIFEST: &str = r#"# GENERATED by `aterm-libc-oracle regen`: the reference libc, documented for
# the declarations and compiled by const-eval probes for the ABI facts. It never
# links and never runs; its own workspace, so it is nobody's member.
[package]
name = "libc-reference"
version = "0.0.0"
edition = "2021"
publish = false

[dependencies]
libc = { version = "=0.2.186", features = ["extra_traits"] }

[lib]
path = "src/lib.rs"

[workspace]
"#;

/// The probe crate's root: each cell's measurement module under its own cfg.
#[must_use]
pub fn lib_rs(cells: &[Cell]) -> String {
    cells
        .iter()
        .map(|cell| format!("#[cfg({})]\nmod {};\n", cell.cfg(), module(cell)))
        .collect()
}

/// The measurement module's name for `cell`.
#[must_use]
pub fn module(cell: &Cell) -> String {
    format!("measure_{}", cell.key)
}

/// One measured fact.
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum Key {
    Size(String),
    Align(String),
    Offset(String, String),
    Byte(String, usize),
    TypeSize(String),
    TypeAlign(String),
}

impl fmt::Display for Key {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Size(name) => write!(f, "SZ {name}"),
            Self::Align(name) => write!(f, "AL {name}"),
            Self::Offset(owner, field) => write!(f, "OF {owner}.{field}"),
            Self::Byte(name, i) => write!(f, "BYTE {name} {i}"),
            Self::TypeSize(ty) => write!(f, "FSZ {ty}"),
            Self::TypeAlign(ty) => write!(f, "FAL {ty}"),
        }
    }
}

/// One pass's source and the fact each of its lines measures.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Probe {
    lines: Vec<String>,
    keys: BTreeMap<usize, Key>,
}

impl Probe {
    fn new() -> Self {
        let mut probe = Self::default();
        probe.line("#![allow(dead_code, non_camel_case_types)]".into());
        probe.line("use libc::*;".into());
        probe
    }

    fn line(&mut self, line: String) {
        self.lines.push(line);
    }

    /// Measure `expr` (a `usize` const expression) as `key`.
    fn measure(&mut self, expr: &str, key: Key) {
        self.lines
            .push(format!("const _: [(); 999999] = [(); {expr}];  // {key}"));
        self.keys.insert(self.lines.len(), key);
    }

    /// The module's text.
    #[must_use]
    pub fn source(&self) -> String {
        let mut out = self.lines.join("\n");
        out.push('\n');
        out
    }

    /// Pair the compiler's reports (1-based line -> value) with this probe's
    /// facts.
    ///
    /// # Errors
    /// The facts no report answered, when any.
    pub fn read(&self, reported: &BTreeMap<usize, u64>) -> Result<BTreeMap<Key, u64>, Vec<Key>> {
        let mut out = BTreeMap::new();
        let mut missing = Vec::new();
        for (line, key) in &self.keys {
            match reported.get(line) {
                Some(value) => {
                    out.insert(key.clone(), *value);
                }
                None => missing.push(key.clone()),
            }
        }
        if missing.is_empty() {
            Ok(out)
        } else {
            Err(missing)
        }
    }
}

/// Pass 1: every named type's size and alignment, every public field's offset.
#[must_use]
pub fn types_and_offsets(decls: &Decls) -> Probe {
    let mut probe = Probe::new();
    let names = decls
        .structs
        .iter()
        .map(|r| &r.name)
        .chain(decls.enums.iter().map(|e| &e.name))
        .chain(decls.unions.iter().map(|r| &r.name))
        .chain(decls.aliases.iter().map(|a| &a.name));
    for name in names {
        let size = format!("::core::mem::size_of::<libc::{name}>()");
        probe.measure(&size, Key::Size(name.clone()));
        let align = format!("::core::mem::align_of::<libc::{name}>()");
        probe.measure(&align, Key::Align(name.clone()));
    }
    for record in decls.structs.iter().chain(&decls.unions) {
        for field in &record.fields {
            let (owner, name) = (&record.name, &field.name);
            let offset = format!("::core::mem::offset_of!(libc::{owner}, {name})");
            probe.measure(&offset, Key::Offset(owner.clone(), name.clone()));
        }
    }
    probe
}

/// Pass 2: the bytes of every constant whose value rustdoc does not state.
///
/// # Errors
/// When such a constant's type was not sized by pass 1, or a value is one the
/// emitter cannot write.
pub fn constant_bytes(decls: &Decls, sizes: &BTreeMap<String, u64>) -> Result<Probe, String> {
    let mut probe = Probe::new();
    for constant in &decls.consts {
        if const_expr(constant)?.is_some() {
            continue;
        }
        let (name, ty) = (&constant.name, &constant.ty);
        let size = *sizes
            .get(ty)
            .ok_or_else(|| format!("{name}: its type `{ty}` was not sized"))?;
        probe.line(format!(
            "const B_{name}: [u8; {size}] = unsafe {{ ::core::mem::transmute(libc::{name}) }};"
        ));
        for i in 0..usize::try_from(size).map_err(|e| e.to_string())? {
            probe.measure(
                &format!("B_{name}[{i}] as usize"),
                Key::Byte(name.clone(), i),
            );
        }
    }
    Ok(probe)
}

/// Pass 3: every field type's size and alignment.
#[must_use]
pub fn field_types(decls: &Decls) -> Probe {
    let mut probe = Probe::new();
    let types: std::collections::BTreeSet<&String> = decls
        .structs
        .iter()
        .chain(&decls.unions)
        .flat_map(|r| r.fields.iter().map(|f| &f.ty))
        .collect();
    for ty in types {
        let size = format!("::core::mem::size_of::<{ty}>()");
        probe.measure(&size, Key::TypeSize(ty.clone()));
        let align = format!("::core::mem::align_of::<{ty}>()");
        probe.measure(&align, Key::TypeAlign(ty.clone()));
    }
    probe
}

/// What a probe line reports: the value an E0308 found in place of 999999.
const FOUND: &str = "expected an array with a size of 999999, found one with a size of ";

/// The values the compiler reported for `file`: each E0308 on a probe line,
/// 1-based line -> the size found.
#[must_use]
pub fn reported(errors: &[Diagnostic], file: &str) -> BTreeMap<usize, u64> {
    errors
        .iter()
        .filter(|error| error.code.as_deref() == Some("E0308"))
        .flat_map(|error| &error.spans)
        .filter(|span| span.primary && span.file.ends_with(file))
        .filter_map(|span| {
            let value = span.label.as_deref()?.strip_prefix(FOUND)?.parse().ok()?;
            Some((span.line, value))
        })
        .collect()
}

/// Why a probe measured less than it asked: the compiler's errors other than
/// the measurements, else the end of cargo's stderr.
#[must_use]
pub fn unmeasured_because(outcome: &Outcome) -> String {
    const SHOWN: usize = 5;
    let other: Vec<&Diagnostic> = outcome
        .errors
        .iter()
        .filter(|error| {
            let measurement = error.code.as_deref() == Some("E0308")
                && error.labels.iter().any(|label| label.starts_with(FOUND));
            !measurement
        })
        .collect();
    if other.is_empty() {
        return tail(&outcome.stderr, 20);
    }
    let mut out: Vec<String> = other
        .iter()
        .take(SHOWN)
        .map(|error| error.rendered.trim_end().to_string())
        .collect();
    if other.len() > SHOWN {
        out.push(format!("… and {} more errors", other.len() - SHOWN));
    }
    out.join("\n")
}

/// Everything the three passes measured on one cell.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Measured {
    pub size: BTreeMap<String, u64>,
    pub align: BTreeMap<String, u64>,
    pub offset: BTreeMap<(String, String), u64>,
    /// Each struct-valued constant's bytes, in order.
    pub bytes: BTreeMap<String, Vec<u8>>,
    /// Each field type's size and alignment.
    pub field_types: TypeSizes,
}

impl Measured {
    /// File one pass's facts.
    ///
    /// # Errors
    /// When a byte measured out of range.
    pub fn record(&mut self, facts: BTreeMap<Key, u64>) -> Result<(), String> {
        for (key, value) in facts {
            match key {
                Key::Size(name) => {
                    self.size.insert(name, value);
                }
                Key::Align(name) => {
                    self.align.insert(name, value);
                }
                Key::Offset(owner, field) => {
                    self.offset.insert((owner, field), value);
                }
                Key::Byte(name, i) => {
                    let byte = u8::try_from(value).map_err(|_| format!("{name}[{i}] = {value}"))?;
                    let bytes = self.bytes.entry(name).or_default();
                    if bytes.len() != i {
                        return Err(format!("byte {i} measured out of order"));
                    }
                    bytes.push(byte);
                }
                Key::TypeSize(ty) => self.field_types.entry(ty).or_default().0 = value,
                Key::TypeAlign(ty) => self.field_types.entry(ty).or_default().1 = value,
            }
        }
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::cells::CELLS;
    use crate::regen::decls::{Const, Field, Record};

    fn decls() -> Decls {
        Decls {
            structs: vec![Record {
                name: "pthread_mutex_t".into(),
                repr: None,
                stripped: true,
                traits: vec![],
                fields: vec![Field {
                    name: "sig".into(),
                    ty: "c_long".into(),
                }],
            }],
            consts: vec![
                Const {
                    name: "PTHREAD_MUTEX_INITIALIZER".into(),
                    ty: "pthread_mutex_t".into(),
                    expr: Some("_".into()),
                    value: None,
                },
                Const {
                    name: "AF_INET".into(),
                    ty: "c_int".into(),
                    expr: Some("2".into()),
                    value: Some("2i32".into()),
                },
            ],
            ..Decls::default()
        }
    }

    #[test]
    fn each_pass_measures_its_facts_one_per_line() {
        let pass1 = types_and_offsets(&decls());
        assert_eq!(
            pass1.source(),
            "#![allow(dead_code, non_camel_case_types)]\nuse libc::*;\n\
             const _: [(); 999999] = [(); ::core::mem::size_of::<libc::pthread_mutex_t>()];  // SZ pthread_mutex_t\n\
             const _: [(); 999999] = [(); ::core::mem::align_of::<libc::pthread_mutex_t>()];  // AL pthread_mutex_t\n\
             const _: [(); 999999] = [(); ::core::mem::offset_of!(libc::pthread_mutex_t, sig)];  // OF pthread_mutex_t.sig\n"
        );
        let sizes = BTreeMap::from([("pthread_mutex_t".to_string(), 2)]);
        let pass2 = constant_bytes(&decls(), &sizes).expect("sized");
        assert_eq!(pass2.keys.len(), 2, "two bytes; AF_INET has a value");
        assert!(pass2.source().contains(
            "const B_PTHREAD_MUTEX_INITIALIZER: [u8; 2] = unsafe { ::core::mem::transmute(libc::PTHREAD_MUTEX_INITIALIZER) };"
        ));
        assert!(constant_bytes(&decls(), &BTreeMap::new()).is_err());
        let pass3 = field_types(&decls());
        assert_eq!(
            pass3.keys.values().collect::<Vec<_>>(),
            [
                &Key::TypeSize("c_long".into()),
                &Key::TypeAlign("c_long".into())
            ]
        );
    }

    /// One E0308 as cargo prints it (captured from a pass-3 probe), plus noise.
    #[test]
    fn the_compilers_reports_are_read_back_to_their_facts() {
        let e0308 = |line: u32, size: u32| {
            format!(
                r#"{{"reason":"compiler-message","message":{{"message":"mismatched types","code":{{"code":"E0308","explanation":"…"}},"level":"error","spans":[{{"file_name":"src/measure_mac.rs","line_start":{line},"is_primary":true,"label":"expected an array with a size of 999999, found one with a size of {size}"}},{{"file_name":"src/measure_mac.rs","line_start":{line},"is_primary":false,"label":"expected because of the type of the constant"}}],"children":[]}}}}"#
            )
        };
        let stdout = [
            e0308(3, 40),
            e0308(4, 8),
            e0308(4, 9).replace("measure_mac", "measure_linux"),
            r#"{"reason":"compiler-message","message":{"message":"aborting","code":null,"level":"error","spans":[]}}"#.into(),
            "   Compiling libc v0.2.186".into(),
        ]
        .join("\n");
        let outcome = Outcome::parse(false, Some(101), &stdout, "");
        let reported = reported(&outcome.errors, "measure_mac.rs");
        assert_eq!(reported, BTreeMap::from([(3, 40), (4, 8)]));
        let pass1 = types_and_offsets(&decls());
        let mut measured = Measured::default();
        assert_eq!(
            pass1.read(&reported),
            Err(vec![Key::Offset("pthread_mutex_t".into(), "sig".into())])
        );
        let all = BTreeMap::from([(3, 40), (4, 8), (5, 0)]);
        measured
            .record(pass1.read(&all).expect("all three"))
            .expect("records");
        assert_eq!(measured.size["pthread_mutex_t"], 40);
        assert_eq!(measured.align["pthread_mutex_t"], 8);
        assert_eq!(
            measured.offset[&("pthread_mutex_t".into(), "sig".into())],
            0
        );
        assert!(
            measured
                .record(BTreeMap::from([(Key::Byte("X".into(), 0), 256)]))
                .is_err()
        );
    }

    /// A probe that measured nothing says why in the compiler's words: cargo
    /// puts them in the JSON on stdout, and stderr holds only its summary.
    #[test]
    fn an_unmeasured_probe_shows_the_errors_that_are_not_measurements() {
        let measurement = r#"{"reason":"compiler-message","message":{"rendered":"error[E0308]: mismatched types","message":"mismatched types","code":{"code":"E0308"},"level":"error","spans":[{"file_name":"src/measure_mac.rs","line_start":3,"is_primary":true,"label":"expected an array with a size of 999999, found one with a size of 40"}]}}"#;
        let unresolved = r#"{"reason":"compiler-message","message":{"rendered":"error[E0425]: cannot find value `B_X` in this scope","message":"cannot find value `B_X` in this scope","code":{"code":"E0425"},"level":"error","spans":[{"file_name":"src/measure_mac.rs","line_start":4,"is_primary":true,"label":"not found in this scope"}]}}"#;
        let stderr = "error: could not compile `libc-reference` (lib) due to 2 previous errors";
        let both = Outcome::parse(
            false,
            Some(101),
            &[measurement, unresolved].join("\n"),
            stderr,
        );
        assert_eq!(
            unmeasured_because(&both),
            "error[E0425]: cannot find value `B_X` in this scope"
        );
        let only_measured = Outcome::parse(false, Some(101), measurement, stderr);
        assert_eq!(unmeasured_because(&only_measured), stderr);
    }

    #[test]
    fn the_probe_root_gates_each_cell_module_on_its_own_cfg() {
        let lib = lib_rs(&CELLS[..1]);
        assert_eq!(
            lib,
            "#[cfg(all(target_os = \"macos\", target_arch = \"aarch64\"))]\nmod measure_mac;\n"
        );
    }
}
